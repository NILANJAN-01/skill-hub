def match_system(name):
    low = name.lower()
    for p, label, shape in _SYS_INDEX:
        if low == p or low.startswith((p + ".", p + "/", p + "::", p + "-")):
            return label, shape
    return None


def _in(name, pool):
    low = name.lower()
