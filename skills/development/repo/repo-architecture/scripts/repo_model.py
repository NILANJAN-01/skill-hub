def _dotted(node):
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = _dotted(node.value)
        return base + "." + node.attr if base else node.attr
    if isinstance(node, ast.Call):
        return _dotted(node.func)
    return ""


_COMPOUND = tuple(getattr(ast, n) for n in ("If", "For", "While", "With", "Try", "AsyncFor", "AsyncWith", "Match",
                                            "TryStar") if hasattr(ast, n))


def _py_nest(body, d=0):
    best = d
    for st in body:
        if isinstance(st, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if isinstance(st, _COMPOUND):
            subs = [getattr(st, f, None) or [] for f in ("body", "orelse", "finalbody")]
            subs += [h.body for h in getattr(st, "handlers", [])] + [c.body for c in getattr(st, "cases", [])]
            for s in subs:
                best = max(best, _py_nest(s, d + 1))
    return best


class _PyVisitor(ast.NodeVisitor):
    def __init__(self, total):
        self.defs, self.imports, self.classes, self.swallow = [], [], [], []
        self.ctx = []      # ("class", name) or ("def", record)
        self.module = {"name": "<module>", "cls": None, "line": 1, "end": total, "public": True, "params": 0,
                       "nest": 0, "ann": [], "sig": "", "calls": [], "pseudo": "module"}
        self.main = None

    def _owner(self):
        for kind, x in reversed(self.ctx):
            if kind == "def":
                return x
        return self.module

    def visit_ClassDef(self, node):
        self.classes.append((node.name, " ".join(_dotted(b) for b in node.bases), node.lineno))
        self.ctx.append(("class", node.name))
        self.generic_visit(node)
        self.ctx.pop()

    def visit_FunctionDef(self, node):
        cls = self.ctx[-1][1] if self.ctx and self.ctx[-1][0] == "class" else None
        a = node.args
        params = len(getattr(a, "posonlyargs", [])) + len(a.args) + len(a.kwonlyargs)
        if cls and a.args and a.args[0].arg in ("self", "cls"):
            params -= 1
        deco, deco_arg = [], ""
        for dn in node.decorator_list:
            deco.append(_dotted(dn))
            if isinstance(dn, ast.Call) and dn.args and isinstance(dn.args[0], ast.Constant) \
                    and isinstance(dn.args[0].value, str) and not deco_arg:
                deco_arg = dn.args[0].value
        name = node.name
        d = {"name": name, "cls": cls, "line": node.lineno, "end": getattr(node, "end_lineno", node.lineno),
             "public": not name.startswith("_") or (name.startswith("__") and name.endswith("__")),
             "params": params, "nest": _py_nest(node.body), "ann": deco, "sig": "def %s(...)" % name,
             "calls": [], "route": deco_arg}
        self.defs.append(d)
        self.ctx.append(("def", d))
        self.generic_visit(node)
        self.ctx.pop()

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_If(self, node):
        t = node.test
        if not self.ctx and isinstance(t, ast.Compare) and isinstance(t.left, ast.Name) and t.left.id == "__name__" \
                and any(isinstance(c, ast.Constant) and c.value == "__main__" for c in t.comparators):
            self.main = {"name": "__main__", "cls": None, "line": node.lineno,
                         "end": getattr(node, "end_lineno", node.lineno), "public": True, "params": 0, "nest": 0,
                         "ann": [], "sig": "", "calls": [], "pseudo": "main"}
            self.ctx.append(("def", self.main))
            self.generic_visit(node)
            self.ctx.pop()
            return
        self.generic_visit(node)

    def visit_Call(self, node):
        f = node.func
        if isinstance(f, ast.Name):
            self._owner()["calls"].append((f.id, None, node.lineno, False))
        elif isinstance(f, ast.Attribute):
            v = f.value
            recv = v.id if isinstance(v, ast.Name) else ("super" if isinstance(v, ast.Call) and
                                                         _dotted(v.func) == "super" else "?")
            self._owner()["calls"].append((f.attr, recv, node.lineno, False))
        self.generic_visit(node)

    def visit_Import(self, node):
        for a in node.names:
            self.imports.append({"kind": "py", "spec": a.name, "level": 0, "names": [], "line": node.lineno,
                                 "alias": a.asname or a.name.split(".")[0]})

    def visit_ImportFrom(self, node):
        self.imports.append({"kind": "py", "spec": node.module or "", "level": node.level or 0,
                             "names": [a.asname or a.name for a in node.names], "orig": [a.name for a in node.names],
                             "line": node.lineno})

    def visit_ExceptHandler(self, node):
        b = node.body
        if node.type is None or (len(b) == 1 and (isinstance(b[0], ast.Pass) or (
                isinstance(b[0], ast.Expr) and isinstance(b[0].value, ast.Constant) and b[0].value.value is Ellipsis))):
            if len(b) == 1 and (isinstance(b[0], (ast.Pass, ast.Expr))):
                self.swallow.append(node.lineno)
        self.generic_visit(node)


def parse_python(text):
    code, bare, comments, doc = lex(text, "Python")
    total = text.count("\n") + 1
    P = {"code": code, "bare": bare, "pkg": None, "comments": [], "comment_lines": doc}
    L = Lines(text)
    P["comments"] = [(L.line(o), t) for o, t in comments]
    P["comment_lines"] += len(comments)
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        tree = None
    if tree is None:          # Python 2 or broken code: indentation-based fallback
        defs = []
        for m in re.finditer(r"(?m)^([ \t]*)(?:async\s+)?def\s+(\w+)\s*\(", bare):
            ind, start = len(m.group(1)), L.line(m.start())
            end = start
            for k in range(start, len(L.starts)):
                line = bare[L.starts[k]:L.starts[k + 1] - 1 if k + 1 < len(L.starts) else len(bare)]
                if line.strip() and len(line) - len(line.lstrip()) <= ind:
                    break
                end = k + 1
            defs.append({"name": m.group(2), "cls": None, "line": start, "end": end,
                         "public": not m.group(2).startswith("_"), "params": 0, "nest": 0, "ann": [], "sig": "",
                         "calls": []})
        for m in _CALL.finditer(bare):
            ln = L.line(m.start())
            owner = next((d for d in reversed(defs) if d["line"] < ln <= d["end"]), None)
            if owner and m.group(1) not in KEYWORDS:
                rm = _RECV.search(bare[max(0, m.start() - 80):m.start()])
                owner["calls"].append((m.group(1), (rm.group(1) or "?") if rm else None, ln, False))
        imports = [{"kind": "py", "spec": m.group(1) or m.group(3), "level": 0, "names": [], "line": L.line(m.start())}
                   for m in re.finditer(r"(?m)^\s*(?:from\s+([\w.]+)\s+import|import\s+([\w.]+))", bare)
                   for _ in [0] if (m.group(1) or m.group(2))]
        for i in imports:
            i["spec"] = i["spec"] or ""
        P.update(defs=defs, imports=imports, classes=[], swallow=[], syntax_error=True)
        return P
    v = _PyVisitor(total)
    v.visit(tree)
    defs = v.defs + ([v.main] if v.main else []) + ([v.module] if v.module["calls"] else [])
    P.update(defs=defs, imports=v.imports, classes=v.classes, swallow=v.swallow)
    return P


def parse_file(lang, text):
    if lang == "Python":
        return parse_python(text)
    if lang in _LANG_DEFS:
        return parse_brace(lang, text)
    code, bare, comments, _ = lex(text, lang)
    L = Lines(text)
    return {"imports": [dict(i, line=L.line(i.pop("pos"))) for i in _imports(lang, code)], "pkg": None, "defs": [],
            "classes": [], "swallow": [], "comments": [(L.line(o), t) for o, t in comments], "code": code,
            "bare": bare, "comment_lines": sum(t.count("\n") + 1 for _, t in comments)}


