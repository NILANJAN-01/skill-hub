def _close(s, i, rx=_BR):
    depth, o = 0, s[i]
    for m in rx.finditer(s, i):
        if m.group() == o:
            depth += 1
        else:
            depth -= 1
            if depth == 0:
                return m.start()
    return len(s) - 1


def _find_body(s, i, fam, init_ok=True, limit=800):
    """From just after a signature's parameters, find the body: ("block", pos of {), ("expr", pos) or None."""
    n, depth, init = len(s), 0, False
    end = min(n, i + limit)
    while i < end:
        c = s[i]
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
            if depth < 0:
                return None
        elif depth == 0:
            if c == "{":
                if init:
                    k = i - 1
                    while k > 0 and s[k] in " \t\n":
                        k -= 1
                    if s[k].isalnum() or s[k] in "_>":
                        i = _close(s, i) + 1
                        continue
                return ("block", i)
            if c in ";}":
                return None
            if c == "=":
                nxt = s[i + 1:i + 2]
                if nxt == ">":
                    if fam not in ("cs", "js", "php"):
                        return None
                    j = i + 2
                    while j < n and s[j] in " \t\n":
                        j += 1
                    return ("block", j) if j < n and s[j] == "{" else ("expr", i + 2)
                if fam == "kotlin" and nxt != "=" and s[i - 1:i] not in "<>!=":
                    return ("expr", i + 1)
                return None
            if c == ":" and fam == "cpp" and init_ok and s[i + 1:i + 2] != ":" and s[i - 1:i] != ":":
                init = True
            if c == "\n":
                j = i + 1
                while j < n and s[j] in " \t\n":
                    j += 1
                if j >= n or not _CONT.match(s, j):
                    return None
                i = j
                continue
        i += 1
    return None


def _expr_end(s, i, limit=3000):
    depth, n, j = 0, min(len(s), i + limit), i
    while j < n:
        c = s[j]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                return j
            depth -= 1
        elif c == ";" and depth == 0:
            return j
        elif c == "\n" and depth == 0:
            k = j + 1
            while k < n and s[k] in " \t":
                k += 1
            if k < n and s[k] in ".?:+-*/|&=":
                j = k
                continue
            if s[i:j].strip():
                return j
        j += 1
    return j


def _params(s, a, b):
    inner = s[a + 1:b].strip()
    if not inner or inner == "void":
        return 0
    depth, commas = 0, 0
    for c in inner:
        if c in "([{<":
            depth += 1
        elif c in ")]}>":
            depth -= 1
        elif c == "," and depth == 0:
            commas += 1
    words = inner.split(",")[0].strip().split()
    selfish = 1 if words and words[0].strip("&*") in ("self", "this", "&self", "&mut") else 0
    return commas + 1 - selfish


def _class_spans(bare, fam, lang):
    spans = []
    for m in _CLASS.finditer(bare):
        kw, rest = m.group("kw"), m.group("rest")
        if fam in ("c", "cpp") and (bare[m.end():m.end() + 1] == "(" or "*" in rest or "&" in rest):
            continue
        if kw == "impl":
            part = rest.split(" for ", 1)[1] if " for " in rest else re.sub(r"^\s*<[^>]*>", "", rest)
            names = _WORD.findall(re.sub(r"<.*", "", part))
            name = names[-1] if names else ""
        else:
            head = re.split(r"[:<(]|\bextends\b|\bimplements\b|\bwhere\b|\bfinal\b", _ANNOT.sub(" ", rest), maxsplit=1)[0]
            names = [w for w in _WORD.findall(head) if w not in _CLASS_MODS]
            # C and C++ put export macros before the name (class API_EXPORT Widget); others put the name first
            name = (names[-1] if fam in ("c", "cpp") else names[0]) if names else ""
        if not name:
            continue
        body = _find_body(bare, m.end(), fam, init_ok=False, limit=1200)
        if not body or body[0] != "block":
            continue
        spans.append((body[1], _close(bare, body[1]), name, rest))
    return spans


def _innermost(spans, pos):
    best = None
    for a, b, name, _ in spans:
        if a < pos < b and (best is None or a > best[0]):
            best = (a, b, name)
    return best[2] if best else None


def _decl_ok(bare, pos, name, cls_here):
    ls = bare.rfind("\n", 0, pos) + 1
    pre = _ANNOT.sub(" ", bare[ls:pos]).strip()
    short = name.split("::")[-1]
    if not pre:
        ps = bare.rfind("\n", 0, max(ls - 1, 0)) + 1
        prev = _ANNOT.sub(" ", bare[ps:max(ls - 1, 0)]).strip()
        words = _WORD.findall(prev)
        if prev and words and _DECL_PREFIX.match(prev) and words[-1] not in _STOP and not prev.endswith(","):
            return True
        return "::" in name or (cls_here is not None and short == cls_here)
    if not _DECL_PREFIX.match(pre):
        return False
    words = _WORD.findall(pre)
    if not words or words[-1] in _STOP or words[0] in _STOP:
        return False
    return True


def _imports(lang, code):
    out = []

    def add(kind, spec, pos, names=(), **kw):
        d = {"kind": kind, "spec": spec, "pos": pos, "names": list(names)}
        d.update(kw)
        out.append(d)

    if lang in ("JavaScript", "TypeScript"):
        for m in re.finditer(r"""(?:\bimport\s+(?:type\s+)?(?P<what>[\w$*{}\s,]+?)\s+from\s+|\bimport\s+|"""
                             r"""\bexport\s+(?:type\s+)?[\w$*{}\s,]+?\s+from\s+|\brequire\s*\(\s*|\bimport\s*\(\s*)"""
                             r"""["'](?P<spec>[^"'\n]+)["']""", code):
            what, names, alias = m.group("what") or "", [], None
            br = re.search(r"\{([^}]*)\}", what)
            if br:
                for part in br.group(1).split(","):
                    bits = part.split(" as ")
                    if bits[-1].strip():
                        names.append(bits[-1].strip())
            star = re.search(r"\*\s+as\s+([\w$]+)", what)
            if star:
                alias = star.group(1)
            add("js", m.group("spec"), m.start(), names, alias=alias)
    elif lang in ("Java", "Kotlin", "Scala", "Groovy"):
        for m in re.finditer(r"(?m)^[ \t]*import\s+(?:static\s+)?(?P<spec>[\w.]+(?:\.\*)?)(?:\s+as\s+(?P<a>\w+))?",
                             code):
            spec = m.group("spec").rstrip(".")
            add("jvm", spec, m.start(), [spec.rsplit(".", 1)[-1]] if not spec.endswith("*") else [])
    elif lang == "Go":
        for m in re.finditer(r"\bimport\s*(?:\(([^)]*)\)|((?:[\w.]+\s+)?\"[^\"]+\"))", code):
            for g in re.finditer(r"(?:([\w.]+)\s+)?\"([^\"]+)\"", m.group(1) or m.group(2)):
                add("go", g.group(2), m.start() + (g.start() if m.group(1) is None else m.start(1) - m.start()
                                                   + g.start()), alias=g.group(1))
    elif lang in ("C", "C++", "Objective-C"):
        for m in re.finditer(r'(?m)^[ \t]*#[ \t]*(?:include|import)[ \t]*([<"])([^>"\n]+)[>"]', code):
            add("c", m.group(2).strip(), m.start(), angle=m.group(1) == "<")
    elif lang == "Rust":
        for m in re.finditer(r"(?m)^[ \t]*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*;", code):
            add("rust_mod", m.group(1), m.start())
        for m in re.finditer(r"(?m)^([ \t]*)(?:pub(?:\([^)]*\))?\s+)?use\s+(?:::)?([\w:]+)", code):
            # an indented `use super::` sits in an inline module (mod tests { ... }): it means this file
            add("rust_use", m.group(2).rstrip(":"), m.start(), nested=bool(m.group(1)))
        for m in re.finditer(r"(?m)^[ \t]*extern\s+crate\s+(\w+)", code):
            add("rust_use", m.group(1), m.start())
    elif lang == "C#":
        for m in re.finditer(r"(?m)^[ \t]*(?:global\s+)?using\s+(?:static\s+)?(?:\w+\s*=\s*)?([\w.]+)\s*;", code):
            add("cs", m.group(1), m.start())
    elif lang == "PHP":
        for m in re.finditer(r"(?m)^[ \t]*use\s+(?:function\s+|const\s+)?([\w\\]+)", code):
            add("php", m.group(1).strip("\\"), m.start())
        for m in re.finditer(r"""\b(?:require|include)(?:_once)?\s*\(?\s*(?:__DIR__\s*\.\s*)?["']([^"']+)["']""", code):
            add("rel", m.group(1).lstrip("/"), m.start(), ext=".php")
    elif lang == "Ruby":
        for m in re.finditer(r"""(?m)^[ \t]*(require_relative|require|load)\s*\(?\s*["']([^"']+)["']""", code):
            add("rel" if m.group(1) == "require_relative" else "ruby", m.group(2), m.start(), ext=".rb")
    elif lang == "Swift":
        for m in re.finditer(r"(?m)^[ \t]*(?:@testable\s+)?import\s+(?:class\s+|struct\s+|func\s+|enum\s+)?(\w+)", code):
            add("swift", m.group(1), m.start())
    elif lang == "Dart":
        for m in re.finditer(r"""(?m)^[ \t]*(?:import|export|part)\s+["']([^"']+)["']""", code):
            add("dart", m.group(1), m.start())
    return out


def _package(lang, code):
    rx = {"Java": r"(?m)^[ \t]*package\s+([\w.]+)", "Kotlin": r"(?m)^[ \t]*package\s+([\w.]+)",
          "Scala": r"(?m)^[ \t]*package\s+([\w.]+)", "Groovy": r"(?m)^[ \t]*package\s+([\w.]+)",
          "Go": r"(?m)^[ \t]*package\s+(\w+)", "C#": r"\bnamespace\s+([\w.]+)",
          "PHP": r"(?m)^[ \t]*namespace\s+([\w\\]+)"}.get(lang)
    m = re.search(rx, code) if rx else None
    return m.group(1) if m else None


def parse_brace(lang, text):
    fam = _FAM[lang]
    code, bare, comments, _ = lex(text, lang)
    if lang in ("C", "C++", "Objective-C", "C#", "Swift"):
        bare = _PREPROC.sub(lambda m: _blank(m.group()), bare)
    L = Lines(text)
    spans = _class_spans(bare, fam, lang)
    cands = {}
    for key, mode in _LANG_DEFS.get(lang, ()):
        for m in _D[key].finditer(bare):
            name = m.group("name") or (m.groupdict().get("init") or "")
            if not name or name in KEYWORDS and mode not in ("kw", "scala"):
                continue
            npos = m.start("name") if m.group("name") else m.start("init")
            last = name.split("::")[-1]
            lpos = npos + len(name) - len(last)
            if lpos in cands:
                continue
            cls = m.groupdict().get("cls")
            cls_here = _innermost(spans, npos)
            if mode == "decl" and not _decl_ok(bare, npos, name, cls_here):
                continue
            ppos = None
            if mode in ("arrow", "obj") and (m.groupdict().get("arrow") or m.groupdict().get("fn")):
                if m.groupdict().get("fn"):
                    ppos = m.end("fn") - 1
                    after = _close(bare, ppos, _PA) + 1
                    body = _find_body(bare, after, fam)
                else:
                    a = m.start("arrow")
                    if bare[a] == "(":
                        ppos = a
                        k = _close(bare, a, _PA) + 1
                        ar = re.compile(r"\s*(?::[^=;{}\n]*)?=>\s*").match(bare, k)
                    else:
                        ar = re.compile(r"[A-Za-z_$][\w$]*\s*=>\s*").match(bare, a)
                    if not ar:
                        continue
                    j = ar.end()
                    body = ("block", j) if bare[j:j + 1] == "{" else ("expr", j)
                if mode == "obj" and (not body or body[0] != "block"):
                    continue
            elif mode == "arrow":
                continue
            else:
                if mode == "scala" and not m.group("paren"):
                    after = m.end()
                else:
                    ppos = m.end() - 1
                    after = _close(bare, ppos, _PA) + 1
                body = _find_body(bare, after, fam)
                if mode == "method" and (not body or body[0] != "block"):
                    continue
            if not body:
                continue
            kind, b = body
            e = _close(bare, b) if kind == "block" else _expr_end(bare, b)
            if "::" in name:
                cls = name.split("::")[-2].split("<")[0] or cls
            if cls and "." in cls:
                cls = cls.rsplit(".", 1)[-1]
            cls = (cls or cls_here or None)
            if cls:
                cls = re.sub(r"[<?].*", "", cls)
            ls = bare.rfind("\n", 0, npos) + 1
            prefix = _WORD.findall(bare[ls:npos])
            if not prefix and ls > 0:
                prefix = _WORD.findall(bare[bare.rfind("\n", 0, ls - 1) + 1:ls])
            if lang == "Go":
                public = last[:1].isupper()
            elif lang == "Rust":
                public = "pub" in prefix
            elif lang in ("C", "C++", "Objective-C"):
                public = "static" not in prefix
            elif lang in ("JavaScript", "TypeScript"):
                public = True
            else:
                public = not ({"private", "fileprivate"} & set(prefix))
            before = code[L.starts[max(0, L.line(npos) - 4)]:npos]
            ann = re.findall(r"@(\w+)", before) + re.findall(r"\[(\w+)(?:\(|\])", before)
            depth = maxd = 0
            if kind == "block":
                for bm in _BR.finditer(bare, b + 1, e):
                    depth += 1 if bm.group() == "{" else -1
                    maxd = max(maxd, depth)
            cands[lpos] = {"name": "~" + last.lstrip("~") if last.startswith("~") else last, "cls": cls,
                           "line": L.line(npos), "end": L.line(e), "_b": b, "_e": e, "public": public,
                           "params": _params(bare, ppos, _close(bare, ppos, _PA)) if ppos is not None else 0,
                           "nest": maxd, "ann": sorted(set(ann)), "sig": code[ls:min(len(code), npos + 120)]
                           .split("\n")[0].strip()[:160], "calls": []}
    defs = [cands[k] for k in sorted(cands, key=lambda p: cands[p]["_b"])]
    if lang in _NO_NEST:
        kept, end = [], -1
        for d in defs:
            if d["_b"] > end:
                kept.append(d)
                end = d["_e"]
        defs = kept
    names_at = set(cands)
    module = {"name": "<module>", "cls": None, "line": 1, "end": L.line(len(text)), "public": True, "params": 0,
              "nest": 0, "ann": [], "sig": "", "calls": [], "pseudo": "module"}
    stack, k = [], 0
    for m in _CALL.finditer(bare):
        p = m.start(1)
        name = m.group(1)
        if p in names_at or name in KEYWORDS and not (name == "new" and bare[max(0, p - 2):p] == "::"):
            continue
        while k < len(defs) and defs[k]["_b"] < p:
            while stack and stack[-1]["_e"] < defs[k]["_b"]:
                stack.pop()
            stack.append(defs[k])
            k += 1
        while stack and stack[-1]["_e"] < p:
            stack.pop()
        owner = stack[-1] if stack else module
        back = bare[max(0, p - 120):p]
        rm = _RECV.search(back)
        recv = (rm.group(1) or "?") if rm else None
        owner["calls"].append((name, recv, L.line(p), bool(_NEWKW.search(back))))
    for d in defs:
        d.pop("_b")
        d.pop("_e")
    if module["calls"] and lang in ("JavaScript", "TypeScript", "PHP", "Kotlin", "Dart"):
        defs.append(module)
    swallow = [L.line(m.start()) for m in re.finditer(
        r"\bcatch\b\s*(?:\([^()]*\))?\s*\{\s*\}" if lang != "Go" else r"\bif\s+err\s*!=\s*nil\s*\{\s*\}", bare)]
    classes = [(name, rest, L.line(a)) for a, _, name, rest in spans]
    return {"imports": [dict(i, line=L.line(i.pop("pos"))) for i in _imports(lang, code)],
            "pkg": _package(lang, code), "defs": defs, "classes": classes, "swallow": swallow,
            "comments": [(L.line(o), t) for o, t in comments], "code": code, "bare": bare,
            "comment_lines": sum(t.count("\n") + 1 for _, t in comments)}


