def build_components(infos, depth=2, granularity="auto", max_groups=24):
    """Group files into components. Returns (comp_of: path -> id, component records)."""
    code = {i["path"]: max(i["lines"], 1) for i in infos if i["role"] == "code" and i["status"] == "read"}
    sub, w, own = defaultdict(set), Counter(), Counter()
    for p, n in code.items():
        parent = ""
        parts = p.split("/")[:-1]
        for k in range(1, len(parts) + 1):
            d = "/".join(parts[:k])
            sub[parent].add(d)
            w[d] += n
            parent = d
        own[parent] += n
    total = sum(code.values()) or 1
    full, owngrp, opened = set(sub[""]), set(), {""}
    if own[""]:
        owngrp.add("")
    changed = True
    while changed:
        changed = False
        for g in sorted(full, key=lambda d: (-w[d], d)):
            kids = sub.get(g)
            if not kids:
                continue
            name = g.rsplit("/", 1)[-1].lower()
            chain = len(kids) == 1 and not own[g]
            container = name in CONTAINER_DIRS and g.count("/") < depth
            dominant = w[g] / total > 0.5 and (len(kids) >= 2 or own[g])
            if not (chain or container or dominant):
                continue
            if not chain and len(full) + len(owngrp) - 1 + len(kids) + (1 if own[g] else 0) > max_groups:
                continue
            full.discard(g)
            opened.add(g)
            full |= kids
            if own[g]:
                owngrp.add(g)
            changed = True
            break
    comp_of = {}

    def assign(p):
        d = _dir(p)
        if d in owngrp:
            return d
        k = d
        while True:
            if k in full:
                return k
            if not k:
                break
            k = _dir(k)
        parts = d.split("/") if d else []
        for n in range(1, len(parts) + 1):
            cand = "/".join(parts[:n])
            if cand not in opened:
                full.add(cand)
                return cand
        owngrp.add(d)
        return d

    for i in infos:
        comp_of[i["path"]] = assign(i["path"])
    # flat project: split the biggest code group into files
    cw = Counter()
    cfiles = defaultdict(list)
    for p, n in code.items():
        cw[comp_of[p]] += n
        cfiles[comp_of[p]].append(p)
    if cw and granularity != "folder":
        big, bw = cw.most_common(1)[0]
        nfiles = len(cfiles[big])
        if granularity == "file" and nfiles >= 2 or \
                granularity == "auto" and 3 <= nfiles <= 60 and (len(cw) < 3 or bw / total > 0.6):
            for p in sorted(cfiles[big])[:80]:
                comp_of[p] = p
    groups = defaultdict(list)
    for i in infos:
        groups[comp_of[i["path"]]].append(i)
    names = unique_names(list(groups))
    comps = []
    for cid, files in groups.items():
        roles = Counter(i["role"] for i in files if i["status"] != "skip")
        langs = Counter()
        for i in files:
            if i["role"] in ("code", "test") and i["status"] == "read" and i["lang"]:
                langs[i["lang"]] += i["lines"]
        segs = {s.lower() for s in cid.split("/")}
        first = {cid.split("/")[0].lower()}
        kind = "source"
        code_l = sum(i["lines"] for i in files if i["role"] == "code" and i["status"] == "read")
        test_l = sum(i["lines"] for i in files if i["role"] == "test" and i["status"] == "read")
        if roles["test"] and (test_l > 1.5 * code_l or not code_l and roles["test"] >= roles["doc"] + roles["data"]):
            kind = "tests"
        else:
            for k, pool in KIND_SEGS:
                if first & pool:
                    kind = k
                    break
            if kind == "source" and not roles["code"]:
                kind = "config" if roles["config"] + roles["build"] >= roles["doc"] + roles["data"] else (
                    "docs" if roles["doc"] >= roles["data"] else "data")
            if kind == "source" and langs and sum(v for l, v in langs.items() if l in (
                    "JavaScript", "TypeScript")) > 0.6 * sum(langs.values()) and segs & {
                    "web", "frontend", "ui", "client", "www", "public", "static", "site", "app", "webapp"}:
                kind = "web"
        comps.append({
            "id": cid, "name": names[cid], "kind": kind, "files": len(files),
            "lines": sum(i["lines"] for i in files if i["status"] == "read"),
            "code_lines": sum(i["lines"] for i in files if i["role"] == "code" and i["status"] == "read"),
            "test_lines": sum(i["lines"] for i in files if i["role"] == "test" and i["status"] == "read"),
            "langs": dict(langs.most_common(4)),
            "key_files": [i["path"] for i in sorted((i for i in files if i["role"] == "code" and i["status"] == "read"),
                                                    key=lambda i: -i["lines"])[:5]],
        })
    comps.sort(key=lambda c: (c["id"] != "", c["id"]))
    return comp_of, comps


NAME_NOISE = {"src", "main", "java", "kotlin", "scala", "com", "org", "net", "io", "lib", "source", "sources", "app",
              "include"}


def unique_names(cids):
    """Short display names: the last meaningful folder, widened only where two would look the same."""
    def segs(cid):
        parts = cid.split("/")
        return [x for x in parts if x.lower() not in NAME_NOISE] or parts[-1:]

    def join(*xs):
        out = []
        for x in xs:
            if x and (not out or out[-1] != x):
                out.append(x)
        return "/".join(out)

    names = {cid: (segs(cid)[-1] if cid else "(root)") for cid in cids}
    for step in range(3):
        groups = defaultdict(list)
        for cid in cids:
            groups[names[cid]].append(cid)
        dups = [g for g in groups.values() if len(g) > 1]
        if not dups:
            break
        for g in dups:
            for cid in g:
                if not cid:
                    continue
                first, last = cid.split("/")[0], segs(cid)[-1]
                if step == 0:
                    names[cid] = join(first, last)
                elif step == 1:
                    others = [set(segs(o)) for o in g if o != cid]
                    mine = [x for x in segs(cid)[:-1] if any(x not in o for o in others) and x != first]
                    names[cid] = join(first, mine[0] if mine else "", last)
                else:
                    names[cid] = cid
    return names


def _sccs(nodes, adj):
    index, low, onstack, stack, out, counter = {}, {}, set(), [], [], [0]
    sys.setrecursionlimit(max(sys.getrecursionlimit(), 10000))

    def strong(v):
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        onstack.add(v)
        for w in adj.get(v, ()):
            if w not in index:
                strong(w)
                low[v] = min(low[v], low[w])
            elif w in onstack:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                onstack.discard(w)
                comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp))

    for v in nodes:
        if v not in index:
            strong(v)
    return out


