# family: (token regex, nested block comments, single quote is "char" or "str", strings span lines)
_FAMSPEC = {
    "c": (r'//|/\*|"|\'', False, "char", False),
    "cpp": (r'(?<![\w])(?:u8|[uUL])?R"[^()\\\s"]{0,16}\(|//|/\*|"|\'', False, "char", False),
    "java": (r'"""|//|/\*|"|\'', False, "char", False),
    "kotlin": (r'"""|//|/\*|"|\'', True, "char", False),
    "go": (r'//|/\*|"|\'|`', False, "char", False),
    "rust": (r'(?<![\w])b?r#*"|//|/\*|"|\'', True, "char", True),
    "cs": (r'"""|(?<![\w])(?:\$@|@\$|@)"|//|/\*|"|\'', False, "char", False),
    "js": (r'//|/\*|"|\'|`', False, "str", False),
    "php": (r'//|#|/\*|"|\'', False, "str", True),
    "py": (r'#|"""|\'\'\'|"|\'', False, "str", False),
    "hash": (r'#|"|\'', False, "str", False),
    "dash": (r'--|"|\'', False, "str", False),
}
_FAM = {"C": "c", "Objective-C": "c", "Zig": "c", "C++": "cpp", "Java": "java", "Groovy": "java",
        "Gradle": "java", "Kotlin": "kotlin", "Scala": "kotlin", "Swift": "kotlin", "Go": "go", "Rust": "rust",
        "C#": "cs", "JavaScript": "js", "TypeScript": "js", "Dart": "js", "PHP": "php", "Python": "py",
        "Ruby": "hash", "Shell": "hash", "Perl": "hash", "R": "hash", "Elixir": "hash", "PowerShell": "hash",
        "Julia": "hash", "Nim": "hash", "Make": "hash", "Dockerfile": "hash", "YAML": "hash", "TOML": "hash",
        "Lua": "dash", "SQL": "dash", "Haskell": "dash"}
_LEXRX = {}
_QRX = {}
_CHAR = re.compile(r"'(?:\\(?:u\{[0-9a-fA-F]{1,6}\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{1,2}|[0-7]{1,3}|.)|[^'\\\n])'")
_NONNL = re.compile(r"[^\n]")
_BLOCKTOK = re.compile(r"/\*|\*/")
_PREPROC = re.compile(r"(?m)^[ \t]*#(?:[^\n\\]|\\[\s\S])*")


def _blank(s):
    return _NONNL.sub(" ", s)


def _qrx(q, multi):
    key = (q, multi)
    if key not in _QRX:
        e = re.escape(q)
        _QRX[key] = re.compile(r"%s(?:[^%s\\%s]|\\.)*(?:%s)?" % (e, e, "" if multi else r"\n", e), re.S)
    return _QRX[key]


def _block_end(text, j, nest):
    if not nest:
        k = text.find("*/", j + 2)
        return len(text) if k < 0 else k + 2
    depth = 0
    for m in _BLOCKTOK.finditer(text, j):
        depth += 1 if m.group() == "/*" else -1
        if depth == 0:
            return m.end()
    return len(text)


def _verbatim_end(text, i):
    while True:
        k = text.find('"', i)
        if k < 0:
            return len(text)
        if text.startswith('""', k):
            i = k + 2
            continue
        return k + 1


def lex(text, lang):
    """Separate code from comments and strings, keeping every offset and line number.

    Returns (code, bare, comments, doc_lines): code has comments blanked, bare also blanks the
    inside of strings, comments is a list of (offset, text), doc_lines counts docstring lines."""
    fam = _FAM.get(lang)
    if not fam:
        return text, text, [], 0
    spec = _FAMSPEC[fam]
    rx = _LEXRX.get(fam) or _LEXRX.setdefault(fam, re.compile(spec[0]))
    nest, sq, multi = spec[1], spec[2], spec[3]
    code, bare, comments = [], [], []
    doc = 0
    i, n = 0, len(text)
    while i < n:
        m = rx.search(text, i)
        if not m:
            code.append(text[i:])
            bare.append(text[i:])
            break
        j, tok = m.start(), m.group()
        if j > i:
            code.append(text[i:j])
            bare.append(text[i:j])
        com = False
        if tok in ("//", "#", "--"):
            e = text.find("\n", j)
            e = n if e < 0 else e
            com = True
        elif tok == "/*":
            e = _block_end(text, j, nest)
            com = True
        elif tok in ('"""', "'''"):
            e = text.find(tok, j + 3)
            e = n if e < 0 else e + 3
            if fam == "py" and not text[text.rfind("\n", 0, j) + 1:j].strip():
                doc += text.count("\n", j, e) + 1
        elif tok == "`":
            e = _qrx("`", True).match(text, j).end() if fam == "js" else (text.find("`", j + 1) + 1 or n)
        elif tok == "'" and sq == "char":
            cm = _CHAR.match(text, j)
            if not cm:
                code.append(tok)
                bare.append(tok)
                i = j + 1
                continue
            e = cm.end()
        elif tok in ("'", '"'):
            e = _qrx(tok, multi).match(text, j).end()
        elif 'R"' in tok:
            delim = tok[tok.index('"') + 1:-1]
            k = text.find(")" + delim + '"', j + len(tok))
            e = n if k < 0 else k + len(delim) + 2
        elif "@" in tok:
            e = _verbatim_end(text, j + len(tok))
        elif tok.endswith('"'):
            close = '"' + "#" * tok.count("#")
            k = text.find(close, j + len(tok))
            e = n if k < 0 else k + len(close)
        else:
            e = j + len(tok)
        seg = text[j:e]
        if com:
            b = _blank(seg)
            code.append(b)
            bare.append(b)
            comments.append((j, seg))
        else:
            code.append(seg)
            bare.append(seg[:1] + _blank(seg[1:-1]) + seg[-1:] if len(seg) > 1 else seg)
        i = e
    return "".join(code), "".join(bare), comments, doc


class Lines:
    def __init__(self, text):
        self.starts = [0] + [m.end() for m in re.finditer("\n", text)]

    def line(self, pos):
        return bisect.bisect_right(self.starts, pos)


