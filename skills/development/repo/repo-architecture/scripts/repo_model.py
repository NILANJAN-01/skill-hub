def _dir(p):
    return p.rsplit("/", 1)[0] if "/" in p else ""


def _norm(p):
    out = []
    for part in p.split("/"):
        if part in ("", "."):
            continue
        if part == "..":
            if out:
                out.pop()
            continue
        out.append(part)
    return "/".join(out)


def _common(a, b):
    n = 0
    for x, y in zip(a.split("/"), b.split("/")):
        if x != y:
            break
        n += 1
    return n


class Resolver:
    """Map an import in one file to files of the repository, or to an outside package name."""

    def __init__(self, paths, parsed, texts):
        self.paths = set(paths)
        self.by_dir = defaultdict(list)
        for p in paths:
            self.by_dir[_dir(p)].append(p)
        self.py = {}
        pkgdirs = {_dir(p) for p in paths if p.rsplit("/", 1)[-1] == "__init__.py"}
        for p in sorted((p for p in paths if p.endswith((".py", ".pyi"))), key=lambda x: (x.count("/"), x)):
            mod = p.rsplit(".", 1)[0]
            parts = mod.split("/")
            if parts[-1] == "__init__":
                parts = parts[:-1]
            for k in range(len(parts)):
                if k == 0 or "/".join(parts[:k]) not in pkgdirs:
                    self.py.setdefault(".".join(parts[k:]), p)
        self.jvm, self.pkg_files = {}, defaultdict(list)
        for p, P in parsed.items():
            pk = P.get("pkg")
            if not pk or not p.endswith((".java", ".kt", ".kts", ".scala", ".groovy", ".cs", ".php")):
                continue
            pk = pk.replace("\\", ".")
            self.pkg_files[pk].append(p)
            stem = p.rsplit("/", 1)[-1].rsplit(".", 1)[0]
            self.jvm.setdefault(pk + "." + stem, p)
            for c in P.get("classes", ()):
                self.jvm.setdefault(pk + "." + c[0], p)
            for d in P.get("defs", ()):
                if not d["cls"] and not d.get("pseudo"):
                    self.jvm.setdefault(pk + "." + d["name"], p)
        self.go_mods = []
        self.crates = []
        self.js_pkgs = {}
        self.dart_pkgs = {}
        for p, t in texts.items():
            name = p.rsplit("/", 1)[-1]
            if name == "go.mod":
                m = re.search(r"(?m)^module\s+(\S+)", t)
                if m:
                    self.go_mods.append((_dir(p), m.group(1)))
            elif name == "Cargo.toml":
                m = re.search(r"(?ms)^\[package\][^\[]*?^name\s*=\s*\"([^\"]+)\"", t)
                self.crates.append((_dir(p), m.group(1).replace("-", "_") if m else ""))
            elif name == "package.json":
                try:
                    j = json.loads(t)
                    if isinstance(j, dict) and isinstance(j.get("name"), str):
                        self.js_pkgs[j["name"]] = _dir(p)
                except ValueError:
                    pass
            elif name == "pubspec.yaml":
                m = re.search(r"(?m)^name:\s*([\w-]+)", t)
                if m:
                    self.dart_pkgs[m.group(1)] = _dir(p)
        self.go_mods.sort(key=lambda x: -len(x[1]))
        self.crates.sort(key=lambda x: -len(x[0]))
        self.by_base = defaultdict(list)
        for p in paths:
            self.by_base[p.rsplit("/", 1)[-1]].append(p)
        self.stem_src = defaultdict(list)
        for p in paths:
            if p.endswith(SRC_EXT):
                self.stem_src[p.rsplit("/", 1)[-1].rsplit(".", 1)[0]].append(p)

    def _closest(self, cands, f):
        return max(cands, key=lambda c: (_common(c, f), -len(c))) if cands else None

    def siblings(self, header):
        """Implementation files of a header (foo.h -> foo.c / foo.cpp), for call resolution."""
        stem = header.rsplit("/", 1)[-1].rsplit(".", 1)[0]
        c = self._closest(self.stem_src.get(stem, []), header)
        return [c] if c else []

    def resolve(self, f, lang, imp):
        """Return (internal target paths, outside package name or None)."""
        k, spec = imp["kind"], imp["spec"]
        if k == "py":
            return self._py(f, spec, imp.get("level", 0), imp.get("orig", imp.get("names", [])))
        if k == "js":
            return self._js(f, spec)
        if k == "jvm":
            return self._jvm(spec)
        if k == "go":
            for d, mod in self.go_mods:
                if spec == mod or spec.startswith(mod + "/"):
                    tdir = _norm(d + "/" + spec[len(mod):])
                    return [p for p in self.by_dir.get(tdir, []) if p.endswith(".go") and not p.endswith("_test.go")], None
            first = spec.split("/")[0]
            return [], (None if "." not in first else "/".join(spec.split("/")[:3]))
        if k == "c":
            local = _norm(_dir(f) + "/" + spec)
            if local in self.paths:
                return [local], None
            base = spec.rsplit("/", 1)[-1]
            cands = [p for p in self.by_base.get(base, []) if p == spec or p.endswith("/" + spec)]
            if cands:
                return [self._closest(cands, f)], None
            if imp.get("angle"):
                return [], (None if spec in _C_STD or spec.startswith(("sys/", "bits/")) or "." not in spec
                            and "/" not in spec else spec)
            return [], None
        if k == "rust_mod":
            name = f.rsplit("/", 1)[-1]
            base = _dir(f) if name in ("mod.rs", "lib.rs", "main.rs") else f[:-3]
            for c in (base + "/" + spec + ".rs", base + "/" + spec + "/mod.rs"):
                if _norm(c) in self.paths:
                    return [_norm(c)], None
            return [], None
        if k == "rust_use":
            if imp.get("nested") and spec.split("::")[0] in ("super", "self"):
                return [], None
            return self._rust(f, spec)
        if k == "cs":
            files = self.pkg_files.get(spec)
            if files:
                return list(files), None
            return [], (None if spec.split(".")[0] in ("System", "Microsoft") and not spec.startswith(
                ("System.Data", "Microsoft.EntityFrameworkCore", "System.Net.Http", "Microsoft.AspNetCore")) else spec)
        if k == "php":
            segs = spec.split("\\")
            for c in self.by_base.get(segs[-1] + ".php", []):
                if c.endswith("/".join(segs[-2:]) + ".php"):
                    return [c], None
            return [], segs[0]
        if k == "rel":
            ext = imp.get("ext", "")
            for c in (_norm(_dir(f) + "/" + spec), _norm(_dir(f) + "/" + spec + ext), _norm(spec)):
                if c in self.paths:
                    return [c], None
            return [], None
        if k == "ruby":
            for c in self.by_base.get(spec.rsplit("/", 1)[-1] + ".rb", []):
                if c.endswith("lib/" + spec + ".rb"):
                    return [c], None
            return [], spec.split("/")[0]
        if k == "swift":
            files = [p for p in self.paths if p.startswith("Sources/" + spec + "/") and p.endswith(".swift")]
            return (files, None) if files else ([], spec)
        if k == "dart":
            if spec.startswith("package:"):
                name, _, rest = spec[8:].partition("/")
                if name in self.dart_pkgs:
                    c = _norm(self.dart_pkgs[name] + "/lib/" + rest)
                    return ([c], None) if c in self.paths else ([], None)
                return [], name
            if spec.startswith("dart:"):
                return [], None
            c = _norm(_dir(f) + "/" + spec)
            return ([c], None) if c in self.paths else ([], None)
        return [], None

    def _py(self, f, spec, level, names):
        if level:
            base = _dir(f)
            for _ in range(level - 1):
                base = _dir(base)
            prefix = base.replace("/", ".")
            full = (prefix + "." + spec if spec else prefix).strip(".")
            out = []
            root = _norm(base + "/" + spec.replace(".", "/")) if spec else base
            for n in names:
                for c in (root + "/" + n + ".py", root + "/" + n + "/__init__.py"):
                    if _norm(c) in self.paths:
                        out.append(_norm(c))
            for c in (root + ".py", root + "/__init__.py"):
                if _norm(c) in self.paths and not out:
                    out.append(_norm(c))
            if not out and full in self.py:
                out.append(self.py[full])
            return out, None
        out = []
        for n in names:
            if spec + "." + n in self.py:
                out.append(self.py[spec + "." + n])
        parts = spec.split(".")
        if not out:
            for k in range(len(parts), 0, -1):
                key = ".".join(parts[:k])
                if key in self.py:
                    out.append(self.py[key])
                    break
        if out:
            return out, None
        top = parts[0]
        if match_system(spec):
            return [], spec
        return [], (None if top in _PY_STD or not top else top)

    def _js(self, f, spec):
        if spec.startswith("."):
            base = _norm(_dir(f) + "/" + spec)
        elif spec.startswith(("@/", "~/")):
            base = "src/" + spec[2:]
        else:
            for name, d in sorted(self.js_pkgs.items(), key=lambda kv: -len(kv[0])):
                if spec == name or spec.startswith(name + "/"):
                    rest = spec[len(name):].lstrip("/")
                    base = _norm(d + "/" + (rest or "src/index"))
                    for e in JS_EXT:
                        if base + e in self.paths:
                            return [base + e], None
                    files = [p for p in self.paths if p.startswith(_norm(d + "/src") + "/")][:1]
                    return files, None
            if spec.startswith("node:") or spec.split("/")[0] in _NODE_STD:
                return [], None
            parts = spec.split("/")
            return [], "/".join(parts[:2]) if spec.startswith("@") else parts[0]
        for e in JS_EXT:
            if base + e in self.paths:
                return [base + e], None
        stem = re.sub(r"\.(js|mjs|cjs|jsx)$", "", base)
        for e in (".ts", ".tsx"):
            if stem + e in self.paths:
                return [stem + e], None
        return [], None

    def _jvm(self, spec):
        if spec.endswith("*"):
            files = self.pkg_files.get(spec[:-2])
            return (list(files), None) if files else ([], spec[:-2])
        parts = spec.split(".")
        for k in range(len(parts), 1, -1):
            key = ".".join(parts[:k])
            if key in self.jvm:
                return [self.jvm[key]], None
        if spec.startswith(("java.lang", "java.util", "java.io", "java.time", "java.math", "java.text", "java.nio",
                            "kotlin.", "scala.", "groovy.")) or spec in ("java", "kotlin"):
            return [], None
        return [], ".".join(parts[:3]) if len(parts) > 3 else spec

    def _rust(self, f, spec):
        segs = [s for s in spec.split("::") if s]
        if not segs:
            return [], None
        root = next((d for d, _ in self.crates if f.startswith(d + "/") or not d), None)
        src = _norm((root or "") + "/src")
        if segs[0] in ("crate", "self", "super"):
            if segs[0] == "crate":
                inner = f[len(root) + 1:] if root else f
                # tests/, benches/ and examples/ files are crates of their own
                base = _dir(f) if inner.startswith(("tests/", "benches/", "examples/")) else src
                rest = segs[1:]
            else:
                name = f.rsplit("/", 1)[-1]
                base = _dir(f) if name in ("mod.rs", "lib.rs", "main.rs") else f[:-3]
                if segs[0] == "super":
                    base = _dir(base)
                rest = segs[1:]
        else:
            crate = next((d for d, n in self.crates if n == segs[0]), None)
            if crate is None:
                return [], (None if segs[0] in ("std", "core", "alloc") else segs[0])
            base, rest = _norm(crate + "/src"), segs[1:]
        for k in range(len(rest), 0, -1):
            path = base + "/" + "/".join(rest[:k])
            for c in (path + ".rs", path + "/mod.rs"):
                if _norm(c) in self.paths:
                    return [_norm(c)], None
        if segs[0] == "crate":   # an item defined in the crate root
            for c in (base + "/lib.rs", base + "/main.rs"):
                if _norm(c) in self.paths and _norm(c) != f:
                    return [_norm(c)], None
        return [], None


