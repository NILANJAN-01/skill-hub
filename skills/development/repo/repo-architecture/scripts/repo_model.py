URL = re.compile(r"^(https?://|ssh://|git://|file://|git@[\w.-]+:)")


def run_git(root, *args, timeout=60):
    try:
        r = subprocess.run(["git", "-C", root] + list(args), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                           timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout.decode("utf-8", "replace") if r.returncode == 0 else None


def repo_name(src):
    name = re.sub(r"\.git$", "", src.rstrip("/\\").replace("\\", "/").rsplit("/", 1)[-1].rsplit(":", 1)[-1])
    return re.sub(r"[^A-Za-z0-9._-]+", "-", name) or "repo"


def open_source(src, out_dir, branch=None, full_history=False):
    """Return the folder to read: src itself, or a clone of a git URL in out_dir/source."""
    if URL.match(src):
        dest = os.path.join(out_dir, "source")
        if os.path.isdir(os.path.join(dest, ".git")):
            return dest
        os.makedirs(out_dir, exist_ok=True)
        cmd = ["git", "clone", "--quiet"] + ([] if full_history else ["--depth", "1"])
        cmd += (["--branch", branch] if branch else []) + [src, dest]
        try:
            r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=900)
        except (OSError, subprocess.SubprocessError) as e:
            raise SystemExit("error: git clone failed: %s" % e)
        if r.returncode != 0:
            raise SystemExit("error: git clone failed: %s" % r.stderr.decode("utf-8", "replace").strip()[-400:])
        return dest
    if not os.path.isdir(src):
        raise SystemExit("error: %s is not a folder or a git URL" % src)
    return src


def list_files(root, use_git=True):
    """Return (sorted relative posix paths, listed_with_git)."""
    if use_git and (run_git(root, "rev-parse", "--is-inside-work-tree") or "").strip() == "true":
        out = run_git(root, "-c", "core.quotepath=off", "ls-files", "-z", "--cached", "--others",
                      "--exclude-standard", timeout=300)
        if out is not None:
            return sorted({p for p in out.split("\0") if p and os.path.lexists(os.path.join(root, p))}), True
    paths = []
    for d, dirs, files in os.walk(root):
        dirs[:] = sorted(x for x in dirs if x not in HARD_SKIP_DIRS)
        rel = os.path.relpath(d, root).replace(os.sep, "/")
        paths += [f if rel == "." else rel + "/" + f for f in files]
    return sorted(paths), False


def select(paths, only=(), exclude=()):
    def hit(p, pats):
        return any(p == x.rstrip("/") or p.startswith(x.rstrip("/") + "/") or fnmatch.fnmatch(p, x)
                   or fnmatch.fnmatch(p.rsplit("/", 1)[-1], x) for x in pats)
    if only:
        paths = [p for p in paths if hit(p, only)]
    if exclude:
        paths = [p for p in paths if not hit(p, exclude)]
    return paths


def read_file(root, rel):
    """Classify one file. Returns (info, text or None). status: read, peek (first lines only) or skip."""
    path = os.path.join(root, *rel.split("/"))
    name = rel.rsplit("/", 1)[-1]
    low = name.lower()
    ext = low.rsplit(".", 1)[1] if "." in low else ""
    lang = language_of(name)
    info = {"path": rel, "lang": lang, "role": file_role(rel, lang), "status": "skip", "reason": "", "lines": 0,
            "size": 0}
    if os.path.islink(path):
        info["reason"] = "symlink"
        return info, None
    if not os.path.isfile(path):
        info["reason"] = "not a file (submodule or missing)"
        return info, None
    info["size"] = size = os.path.getsize(path)
    if is_sensitive(name):
        info["reason"] = "sensitive"
        return info, None
    if ext in BINARY_EXT:
        info["reason"] = "binary"
        return info, None
    if size > MAX_BYTES:
        info["reason"] = "too large"
        return info, None
    with io.open(path, "rb") as f:
        data = f.read()
    if data[:2] not in (b"\xff\xfe", b"\xfe\xff") and b"\0" in data[:8192]:
        info["reason"] = "binary"
        return info, None
    text = decode(data)
    n = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
    info["lines"] = n
    if not text.strip():
        info["reason"] = "empty"
        return info, None
    if any(p.lower() in VENDORED_DIRS for p in rel.split("/")[:-1]):
        info["reason"] = "vendored"
        return info, None
    if low in LOCKFILES or low.endswith(".lock"):
        info["reason"] = "lockfile"
        return info, None
    if ext in ("js", "mjs", "css", "json", "html") and size / max(n, 1) > 300:
        info["reason"] = "minified"
        return info, None
    head = "\n".join(text.split("\n", 6)[:6])
    if any(fnmatch.fnmatch(low, g) for g in GENERATED_GLOBS) or GENERATED_MARK.search(head):
        info.update(status="peek", reason="generated", peek=min(n, 40))
        return info, None
    if ext in DATA_EXT and n > 400 and lang != "Markdown":
        info.update(status="peek", reason="large data file", peek=60)
        return info, None
    info["status"] = "read"
    keep = info["role"] in ("code", "test") or (info["role"] != "data" and size <= TEXT_LIMIT)
    return info, (text if keep else None)


def collect(root, only=(), exclude=(), include=(), use_git=True, skip=()):
    """List and classify every file. include: globs to read in full even if generated, data or vendored."""
    paths, used_git = list_files(root, use_git)
    skip = [s.rstrip("/") for s in skip if s and s != "."]
    paths = [p for p in paths if not any(p == s or p.startswith(s + "/") for s in skip)]
    paths = select(paths, only, exclude)
    infos, texts = [], {}
    for rel in paths:
        info, text = read_file(root, rel)
        if include and info["status"] != "read" and info["reason"] in ("generated", "large data file", "vendored",
                                                                       "lockfile", "minified") \
                and any(fnmatch.fnmatch(rel, g) or rel.startswith(g.rstrip("/") + "/") for g in include):
            with io.open(os.path.join(root, *rel.split("/")), "rb") as f:
                text = decode(f.read())
            info.update(status="read", reason="")
            info.pop("peek", None)
        infos.append(info)
        if text is not None and info["status"] == "read":
            texts[rel] = text
    cxx = sum(1 for i in infos if i["lang"] == "C++")
    cc = sum(1 for i in infos if i["lang"] == "C" and not i["path"].endswith(".h"))
    if cxx > cc:
        for i in infos:
            if i["path"].endswith(".h"):
                i["lang"] = "C++"
    return infos, texts, used_git


def git_facts(root):
    facts = {}
    head = run_git(root, "rev-parse", "--short", "HEAD")
    if not head:
        return facts
    facts["head"] = head.strip()
    branch = run_git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if branch:
        facts["branch"] = branch.strip()
    remote = run_git(root, "config", "--get", "remote.origin.url")
    if remote:
        facts["remote"] = re.sub(r"//[^/@\s]+@", "//", remote.strip())
    count = run_git(root, "rev-list", "--count", "HEAD")
    if count and count.strip().isdigit():
        facts["commits"] = int(count.strip())
    last = run_git(root, "log", "-1", "--format=%cs")
    first = run_git(root, "log", "--reverse", "--format=%cs", "--max-parents=0")
    if last:
        facts["last_commit"] = last.strip()
    if first and first.strip():
        facts["first_commit"] = first.strip().splitlines()[0]
    if (run_git(root, "rev-parse", "--is-shallow-repository") or "").strip() == "true":
        facts["shallow"] = True
    log = run_git(root, "-c", "core.quotepath=off", "log", "-n", "1000", "--name-only", "--format=", timeout=120)
    if log:
        counts = Counter(x.strip() for x in log.splitlines() if x.strip())
        facts["most_changed"] = [{"path": p, "commits": n} for p, n in
                                 sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:15] if n > 1]
    return facts


