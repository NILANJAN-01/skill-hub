def _lineno(text, pos):
    return text.count("\n", 0, pos) + 1


def parse_deps(texts):
    deps = []

    def add(eco, name, spec, f, line, dev=False):
        deps.append({"eco": eco, "name": name, "spec": (spec or "").strip(), "file": f, "line": line, "dev": dev})

    for f in sorted(texts):
        low = f.rsplit("/", 1)[-1].lower()
        t = texts[f]
        try:
            if low.startswith("requirements") and low.endswith((".txt", ".in")):
                for n, line in enumerate(t.split("\n"), 1):
                    s = line.split(" #", 1)[0].split("#", 1)[0].strip() if not line.lstrip().startswith("#") else ""
                    if not s or s.startswith(("-", "git+", "http", ".", "/")):
                        continue
                    m = re.match(r"([A-Za-z0-9][\w.-]*)(\[[^\]]*\])?\s*([^;]*)", s)
                    if m:
                        add("pip", m.group(1), m.group(3), f, n, "dev" in low or "test" in low)
            elif low == "pyproject.toml":
                for sec in re.finditer(r"(?ms)^\[project\].*?^dependencies\s*=\s*\[(.*?)\]", t):
                    for m in re.finditer(r"[\"']([A-Za-z0-9][\w.-]*)(?:\[[^\]]*\])?\s*([^\"';]*)", sec.group(1)):
                        add("pip", m.group(1), m.group(2), f, _lineno(t, sec.start(1) + m.start()))
                for sec in re.finditer(r"(?ms)^\[tool\.poetry\.(dev-)?dependencies\]\s*$(.*?)(?=^\[|\Z)", t):
                    for m in re.finditer(r"(?m)^([A-Za-z0-9][\w.-]*)\s*=\s*(?:\"([^\"]*)\"|\{([^}]*)\})", sec.group(2)):
                        if m.group(1).lower() == "python":
                            continue
                        spec = m.group(2) if m.group(2) is not None else (
                            re.search(r"version\s*=\s*\"([^\"]*)\"", m.group(3) or "") or re.match("", "")).group(
                            1) if m.group(3) and "version" in m.group(3) else (m.group(2) or "path/git")
                        add("poetry", m.group(1), spec, f, _lineno(t, sec.start(2) + m.start()), bool(sec.group(1)))
            elif low == "setup.py":
                m = re.search(r"install_requires\s*=\s*\[(.*?)\]", t, re.S)
                if m:
                    for s in re.finditer(r"[\"']([A-Za-z0-9][\w.-]*)(?:\[[^\]]*\])?\s*([^\"';]*)", m.group(1)):
                        add("pip", s.group(1), s.group(2), f, _lineno(t, m.start(1) + s.start()))
            elif low == "package.json":
                j = json.loads(t)
                for key, dev in (("dependencies", False), ("devDependencies", True), ("optionalDependencies", False)):
                    for name, spec in (j.get(key) or {}).items():
                        add("npm", name, spec if isinstance(spec, str) else "", f, _lineno(t, max(t.find('"%s"' % name), 0)), dev)
            elif low == "go.mod":
                for m in re.finditer(r"(?m)^\s*(?:require\s+)?([\w.-]+\.[\w.-]+/[^\s]+)\s+(v[^\s]+)", t):
                    add("go", m.group(1), m.group(2), f, _lineno(t, m.start()))
            elif low == "cargo.toml":
                for sec in re.finditer(r"(?ms)^\[((?:workspace\.)?(?:dev-|build-)?dependencies)\]\s*$(.*?)(?=^\[|\Z)", t):
                    for m in re.finditer(r"(?m)^([A-Za-z0-9][\w-]*)\s*=\s*(?:\"([^\"]*)\"|\{([^}\n]*)\})", sec.group(2)):
                        spec = m.group(2)
                        if spec is None:
                            v = re.search(r"version\s*=\s*\"([^\"]*)\"", m.group(3) or "")
                            spec = v.group(1) if v else ("path/git" if re.search(r"\b(path|git|workspace)\b",
                                                                                 m.group(3) or "") else "")
                        add("cargo", m.group(1), spec, f, _lineno(t, sec.start(2) + m.start()), "dev" in sec.group(1))
            elif low in ("build.gradle", "build.gradle.kts"):
                for m in re.finditer(r"\b(\w*(?:[Ii]mplementation|api|compile|kapt|ksp|annotationProcessor|"
                                     r"[Rr]untimeOnly|[Cc]ompileOnly))\s*\(?\s*[\"']([^:\"'\s]+):([^:\"'\s]+)(?::([^\"'\s]*))?"
                                     r"[\"']", t):
                    add("gradle", m.group(2) + ":" + m.group(3), m.group(4) or "(managed)", f, _lineno(t, m.start()),
                        "test" in m.group(1).lower())
            elif low == "libs.versions.toml":
                for m in re.finditer(r"(?m)^\s*[\w.-]+\s*=\s*\{[^}\n]*module\s*=\s*\"([^\"]+)\"", t):
                    add("gradle", m.group(1), "(catalog)", f, _lineno(t, m.start()))
            elif low == "pom.xml":
                for m in re.finditer(r"<dependency>(.*?)</dependency>", t, re.S):
                    g = re.search(r"<groupId>([^<]+)</groupId>", m.group(1))
                    a = re.search(r"<artifactId>([^<]+)</artifactId>", m.group(1))
                    v = re.search(r"<version>([^<]+)</version>", m.group(1))
                    s = re.search(r"<scope>([^<]+)</scope>", m.group(1))
                    if g and a:
                        add("maven", g.group(1) + ":" + a.group(1), v.group(1) if v else "(managed)", f,
                            _lineno(t, m.start()), bool(s and s.group(1) == "test"))
            elif low.endswith((".csproj", ".fsproj", ".vbproj")) or low == "directory.packages.props":
                for m in re.finditer(r"<Package(?:Reference|Version)\s+Include=\"([^\"]+)\"(?:\s+Version=\"([^\"]*)\")?", t):
                    add("nuget", m.group(1), m.group(2) or "(managed)", f, _lineno(t, m.start()))
            elif low == "gemfile":
                for m in re.finditer(r"(?m)^\s*gem\s+[\"']([^\"']+)[\"'](?:\s*,\s*[\"']([^\"']+)[\"'])?", t):
                    add("gem", m.group(1), m.group(2) or "", f, _lineno(t, m.start()))
            elif low == "composer.json":
                j = json.loads(t)
                for key in ("require", "require-dev"):
                    for name, spec in (j.get(key) or {}).items():
                        if name != "php" and not name.startswith("ext-"):
                            add("composer", name, spec, f, _lineno(t, max(t.find('"%s"' % name), 0)), key != "require")
            elif low == "pubspec.yaml":
                for sec in re.finditer(r"(?ms)^(dev_)?dependencies:\s*$(.*?)(?=^\S|\Z)", t):
                    for m in re.finditer(r"(?m)^  ([\w-]+):[ \t]*([^\n#]*)", sec.group(2)):
                        if m.group(1) not in ("flutter", "sdk"):
                            add("pub", m.group(1), m.group(2).strip() or "(nested)", f,
                                _lineno(t, sec.start(2) + m.start()), bool(sec.group(1)))
            elif low == "vcpkg.json":
                j = json.loads(t)
                for d in j.get("dependencies") or []:
                    add("vcpkg", d if isinstance(d, str) else d.get("name", "?"), "(baseline)", f, 1)
            elif low == "conanfile.txt":
                for m in re.finditer(r"(?m)^([\w.+-]+)/([\w.+-]+)", t):
                    add("conan", m.group(1), m.group(2), f, _lineno(t, m.start()))
            elif low == "cmakelists.txt":
                for m in re.finditer(r"(?i)\bfind_package\s*\(\s*([\w:]+)(?:\s+([\d.]+))?", t):
                    add("cmake", m.group(1), m.group(2) or "(system)", f, _lineno(t, m.start()))
            elif low == "package.swift":
                for m in re.finditer(r"\.package\s*\(\s*(?:name:\s*\"[^\"]*\"\s*,\s*)?url:\s*\"([^\"]+)\"\s*,\s*([^)]*)\)", t):
                    add("swift", m.group(1).rstrip("/").rsplit("/", 1)[-1].replace(".git", ""), m.group(2), f,
                        _lineno(t, m.start()))
        except (ValueError, AttributeError, TypeError):
            continue
    return deps


def _pin_state(d):
    eco, spec = d["eco"], d["spec"].strip().strip("\"'")
    low = spec.lower()
    if eco in ("go", "vcpkg", "cmake", "conan") or spec.startswith("(") or low in ("path/git",):
        return "ok"
    if low in ("*", "latest", "x", "next", "any", "dev-master", "dev-main", "release", "latest.release") \
            or spec.endswith("+") or "LATEST" in spec or spec == "RELEASE" or (eco == "npm" and low in ("", "x.x")):
        return "wild"
    if eco == "npm" and re.match(r"(file|link|workspace|git|github|https?):", low):
        return "ok"
    if not spec:
        return "none"
    return "ok"


def find_commands(texts, paths):
    cmds = []
    pset = set(paths)

    def add(cmd, src):
        if all(c["cmd"] != cmd for c in cmds) and len(cmds) < 24:
            cmds.append({"cmd": cmd, "source": src})

    for f in sorted(texts, key=lambda p: (p.count("/"), p)):
        low = f.rsplit("/", 1)[-1].lower()
        t = texts[f]
        if f.count("/") > 1:
            continue
        if low == "package.json":
            try:
                scripts = (json.loads(t).get("scripts") or {})
            except (ValueError, AttributeError):
                scripts = {}
            pref = [k for k in ("build", "start", "dev", "test", "lint") if k in scripts]
            for k in (pref + [k for k in scripts if k not in pref])[:8]:
                add("npm run " + k if k not in ("start", "test") else "npm " + k, f)
        elif low in ("makefile", "gnumakefile"):
            for m in list(re.finditer(r"(?m)^([A-Za-z][\w.-]*)\s*:(?!=)", t))[:8]:
                add("make " + m.group(1), f)
        elif low == "pyproject.toml":
            sec = re.search(r"(?ms)^\[project\.scripts\]\s*$(.*?)(?=^\[|\Z)", t)
            for m in re.finditer(r"(?m)^([\w.-]+)\s*=", sec.group(1) if sec else ""):
                add(m.group(1), f)
            if "[tool.pytest" in t:
                add("python -m pytest", f)
        elif low == "go.mod":
            add("go build ./...", f)
            add("go test ./...", f)
        elif low == "cargo.toml":
            add("cargo build", f)
            add("cargo test", f)
        elif low == "cmakelists.txt":
            add("cmake -S . -B build && cmake --build build", f)
            if "enable_testing" in t:
                add("ctest --test-dir build", f)
        elif low == "pom.xml":
            add("mvn package", f)
        elif low in ("build.gradle", "build.gradle.kts"):
            wrapper = (_dir(f) + "/gradlew").lstrip("/") in pset
            add(("./gradlew" if wrapper else "gradle") + " build", f)
            add(("./gradlew" if wrapper else "gradle") + " test", f)
        elif low.endswith((".sln", ".csproj")):
            add("dotnet build", f)
            add("dotnet test", f)
        elif low == "tox.ini":
            add("tox", f)
        elif low == "noxfile.py":
            add("nox", f)
        elif low.startswith("dockerfile"):
            add("docker build -t app .", f)
        elif low in ("docker-compose.yml", "docker-compose.yaml", "compose.yaml", "compose.yml"):
            add("docker compose up", f)
        elif low == "justfile":
            for m in list(re.finditer(r"(?m)^([A-Za-z][\w-]*)\s*(?:[\w\s]*):", t))[:6]:
                add("just " + m.group(1), f)
    return cmds


