def _secret_ok(value):
    if _PLACEHOLDER.search(value):
        return False
    if re.fullmatch(r"[a-z]+(?:[-_.][a-z]+)+|[A-Z_]+|[\w.-]+\.(?:com|org|net|io|json|txt|py|js)", value):
        return False
    classes = sum(1 for rx in (r"[a-z]", r"[A-Z]", r"[0-9]", r"[^A-Za-z0-9]") if re.search(rx, value))
    counts = Counter(value)
    entropy = -sum(c / len(value) * math.log(c / len(value), 2) for c in counts.values())
    return len(set(value)) >= 6 and (classes >= 3 or classes == 2 and len(value) >= 20 and entropy >= 3.5)


def mask(value):
    return value[:4] + "..." + " (%d chars)" % len(value)


class Findings:
    CAP = 200

    def __init__(self):
        self.items = []
        self.counts = Counter()

    def add(self, rule, file="", line=0, msg="", test=False):
        sev = RULES[rule][1]
        if test:
            if sev == "LOW":
                return
            sev = "MEDIUM" if sev == "HIGH" else "LOW"
            msg = (msg + " (test code)").strip()
        self.counts[rule] += 1
        if self.counts[rule] <= self.CAP:
            self.items.append({"rule": rule, "sev": sev, "file": file, "line": line, "msg": msg})


def file_checks(info, text, P, F):
    """Per-file audit checks on parsed code."""
    path, lang, test = info["path"], info["lang"], info["role"] == "test"
    code = P.get("code") or ""
    bare = P.get("bare") or code
    L = Lines(code) if code else None
    for rule, langs, rx, strings in _SEC:
        if langs is not None and lang not in langs:
            continue
        if test and rule in ("SEC010", "SEC011", "SEC012"):
            continue
        hits = 0
        src = code if strings else bare
        for m in rx.finditer(src):
            F.add(rule, path, L.line(m.start()), code[m.start():m.end()].strip()[:80], test)
            hits += 1
            if hits >= 10:
                break
    for ln in P.get("swallow", ())[:10]:
        F.add("COD004", path, ln, "empty catch/except block", test)
    if test:
        return
    marks = 0
    for ln, t in P.get("comments", ()):
        m = re.search(r"\b(TODO|FIXME|HACK|XXX)\b[:\s]*(.{0,60})", t)
        if m and marks < 20:
            F.add("COD005", path, ln, (m.group(1) + " " + m.group(2)).strip())
            marks += 1
    if info["lines"] > 1000:
        F.add("COD001", path, 1, "%d lines" % info["lines"])
    if info["lines"] > 300 and P.get("comment_lines", 0) < 0.02 * info["lines"]:
        F.add("DOC005", path, 1, "%d comment lines in %d" % (P.get("comment_lines", 0), info["lines"]))


def text_checks(info, text, F):
    """Secrets and merge markers in any text file that is read."""
    if info["role"] not in ("code", "test", "config", "build"):
        return
    path, test = info["path"], info["role"] == "test"
    L = None
    hits = 0
    for label, rx in _SECRETS:
        for m in rx.finditer(text):
            value = m.group(m.lastindex) if m.lastindex else m.group(0)
            if label in ("password in URL", "secret value"):
                if not _secret_ok(value):
                    continue
            elif re.search(r"(?i)example|sample|dummy|placeholder|fake|xxxx", value):
                continue
            L = L or Lines(text)
            F.add("SEC001", path, L.line(m.start()), "%s: %s" % (label, mask(value) if label != "private key"
                                                                   else "key block"), test)
            hits += 1
            if hits >= 10:
                return
    if "<<<<<<< " in text and ">>>>>>> " in text and info["role"] in ("code", "config", "build"):
        m = re.search(r"(?m)^<{7} \S*", text)
        if m:
            F.add("HYG004", path, (L or Lines(text)).line(m.start()), "conflict markers")


