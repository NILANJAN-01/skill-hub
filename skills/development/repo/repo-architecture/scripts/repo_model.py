def language_of(name):
    low = name.lower()
    if low in NAME_LANG:
        return NAME_LANG[low]
    if low.startswith("dockerfile"):
        return "Dockerfile"
    if low.endswith(".gradle.kts"):
        return "Gradle"
    return EXT_LANG.get(low.rsplit(".", 1)[1], "") if "." in low else ""


def is_sensitive(name):
    low = name.lower()
    if low.endswith(SENSITIVE_SAFE):
        return False
    return low in SENSITIVE_NAMES or any(fnmatch.fnmatch(low, g) for g in SENSITIVE_GLOBS)


def is_ci(rel):
    low = rel.lower()
    return any(low.startswith(p) or low == p.rstrip("/") for p in CI_PATTERNS)


_TEST_DIR = re.compile(r"(?i)(?:^|[._-])(?:tests?|specs?)$|Tests$")


def is_test_path(rel):
    parts = rel.split("/")
    return any(p.lower() in TEST_DIRS or _TEST_DIR.search(p) for p in parts[:-1]) or bool(TEST_FILE.search(parts[-1]))


def file_role(rel, lang):
    name = rel.rsplit("/", 1)[-1].lower()
    if is_ci(rel) or name in BUILD_NAMES or name.startswith(("requirements", "dockerfile")) or lang == "Gradle" \
            or name.endswith((".csproj", ".sln", ".fsproj", ".vcxproj", ".cabal", ".gemspec", ".podspec")):
        return "build"
    if is_test_path(rel):
        return "test"
    if lang in CODE_LANGS:
        return "code"
    if lang in DOC_LANGS:
        return "doc"
    if lang in CONFIG_LANGS:
        return "config"
    return "data"


def decode(data):
    if data[:3] == b"\xef\xbb\xbf":
        data = data[3:]
    text = None
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        try:
            text = data.decode("utf-16")
        except UnicodeDecodeError:
            text = None
    if text is None:
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            text = data.decode("latin-1")
    return text.replace("\r\n", "\n").replace("\r", "\n")


