def def_label(d):
    if d.get("pseudo") == "main":
        return "__main__ block"
    if d.get("pseudo") == "module":
        return "module code"
    return ("%s.%s()" % (d["cls"], d["name"])) if d["cls"] else d["name"] + "()"


class Analysis:
    """Everything analyze() learns, kept in memory; to_model() makes the JSON-able model."""


def analyze(root, name=None, source=None, depth=2, granularity="auto", flows=3, steps=30, only=(), exclude=(),
            include=(), use_git=True, skip=()):
    t0 = time.time()
    title = name
    infos, texts, used_git = collect(root, only, exclude, include, use_git, skip)
    F = Findings()
    parsed, words, notes = {}, Counter(), []
    parse_errors = 0
    for info in infos:
        text = texts.get(info["path"])
        if text is None:
            continue
        text_checks(info, text, F)
        if info["role"] in ("code", "test") and info["lang"] in CODE_LANGS:
            if info["lines"] > PARSE_LIMIT:
                notes.append("Not parsed (over %d lines): %s" % (PARSE_LIMIT, info["path"]))
                continue
            P = parse_file(info["lang"], text)
            parse_errors += 1 if P.get("syntax_error") else 0
            file_checks(info, text, P, F)
            words.update(_WORD.findall(P.pop("bare")))
            P.pop("code", None)
            P.pop("comments", None)
            parsed[info["path"]] = P
            info["symbols"] = [def_label(d) for d in P["defs"] if not d.get("pseudo")][:40]
    if parse_errors:
        notes.append("%d Python file(s) did not parse (Python 2 or syntax errors); a simpler reader was used."
                     % parse_errors)
    by_path = {i["path"]: i for i in infos}
    paths = [i["path"] for i in infos]
    comp_of, comps = build_components(infos, depth, granularity)
    cindex = {c["id"]: c for c in comps}
    R = Resolver(paths, parsed, texts)

    # ---- imports: file and component edges, outside packages
    imp_files, imp_names, aliases, linked = defaultdict(set), defaultdict(dict), defaultdict(dict), defaultdict(set)
    edge_w = Counter()
    file_edges = Counter()
    ext_by_comp = defaultdict(Counter)
    tested = set()
    for f, P in parsed.items():
        lang = by_path[f]["lang"]
        cf = comp_of[f]
        for imp in P["imports"]:
            targets, ext = R.resolve(f, lang, imp)
            targets = [t for t in targets if t != f]
            for t in targets:
                imp_files[f].add(t)
                file_edges[(f, t)] += 1
                if t.endswith((".h", ".hpp", ".hh", ".hxx")):
                    linked[f].update(R.siblings(t))
                ct = comp_of.get(t)
                if ct is not None and ct != cf and imp["kind"] != "rust_mod":
                    edge_w[(cf, ct)] += 1
                if by_path[f]["role"] == "test" and ct is not None:
                    tested.add(ct)
            if targets:
                for n in imp.get("names", ()):
                    imp_names[f].setdefault(n, targets[0])
                al = imp.get("alias") or (imp["spec"].rsplit("/", 1)[-1] if imp["kind"] == "go" else None)
                if al:
                    aliases[f].setdefault(al, set()).update(targets)
            if ext and by_path[f]["role"] != "test":
                ext_by_comp[cf][ext] += 1
    comp_deps = defaultdict(set)
    for (a, b) in edge_w:
        comp_deps[a].add(b)

    # ---- functions and calls
    defs = []
    for f, P in parsed.items():
        for d in P["defs"]:
            d["file"] = f
            defs.append(d)
    by_name, ctors = defaultdict(list), defaultdict(list)
    for i, d in enumerate(defs):
        if not d.get("pseudo"):
            by_name[d["name"]].append(i)
            if d["cls"] and d["name"] in (d["cls"], "__init__", "constructor", "init"):
                ctors[d["cls"]].append(i)
    graph = [[] for _ in defs]
    test_def = [by_path[d["file"]]["role"] == "test" for d in defs]
    called = Counter()
    total_calls = resolved = 0
    same_pkg_langs = {"Go", "Java", "Kotlin", "Scala", "Groovy", "C#", "Swift", "Dart"}
    for i, d in enumerate(defs):
        f = d["file"]
        lang = by_path[f]["lang"]
        seen = set()
        names, imp, link, al = imp_names.get(f, {}), imp_files.get(f, ()), linked.get(f, ()), aliases.get(f, {})
        cf = comp_of[f]
        test_caller = by_path[f]["role"] == "test"
        for name, recv, line, ctor in d["calls"]:
            total_calls += 1
            cands = by_name.get(name, ())
            if name in ctors and (ctor or not cands or recv is None and name[:1].isupper()):
                cands = ctors[name]
            if not test_caller:
                cands = [k for k in cands if not test_def[k]]
            if not cands or len(cands) > 80:
                continue
            selfish = recv in (None, "self", "this", "cls", "super", "Self", "$this", "static")
            best, bs, second = None, -99, -99
            for k in cands:
                c = defs[k]
                g = c["file"]
                s = 0
                if names.get(name) == g:
                    s += 6
                if g == f:
                    s += 4
                elif g in imp or g in link:
                    s += 3
                elif lang in same_pkg_langs and _dir(g) == _dir(f):
                    s += 2
                gc = comp_of.get(g)
                s += 1 if gc == cf or gc in comp_deps[cf] else 0
                if recv and recv in al and g in al[recv]:
                    s += 5
                if c["cls"]:
                    if selfish and recv is not None and d["cls"] == c["cls"]:
                        s += 3
                    elif selfish and recv is None and d["cls"] == c["cls"]:
                        s += 2
                    elif recv and not selfish:
                        r, kc = recv.lower(), c["cls"].lower()
                        if r == kc:
                            s += 4
                        elif len(r) >= 3 and (kc.endswith(r) or kc.startswith(r) or r.endswith(kc)):
                            s += 2
                    elif recv in ("self", "this") and d["cls"] != c["cls"]:
                        s -= 1
                elif recv and not selfish and recv not in al and lang not in ("Go",):
                    stem = g.rsplit("/", 1)[-1].rsplit(".", 1)[0]
                    s += 3 if recv == stem else -1
                if s > bs:
                    second, bs, best = bs, s, k
                elif s > second:
                    second = s
            if best is None or best == i:
                continue
            if len(cands) == 1:
                if bs < 1 and (name in COMMON or len(name) < 4 or (recv and not selfish)):
                    continue
            elif not (bs >= 3 and bs > second):
                continue
            resolved += 1
            called[best] += 1
            if best not in seen:
                seen.add(best)
                graph[i].append((best, line))

    # ---- entry points
    routes = defaultdict(set)
    for f, t in texts.items():
        lang = by_path[f]["lang"]
        if lang == "Go":
            for m in re.finditer(r"\.(?:HandleFunc|Handle|GET|POST|PUT|DELETE|PATCH|Get|Post|Put|Delete|Patch|Any)\s*"
                                 r"\(\s*\"[^\"]*\"\s*,\s*([A-Za-z_][\w.]*)\s*\)", t):
                routes[f].add(m.group(1).rsplit(".", 1)[-1])
        elif lang in ("JavaScript", "TypeScript"):
            for m in re.finditer(r"\b(?:app|router|server|api|r)\.(?:get|post|put|delete|patch|all|route)\s*\(\s*"
                                 r"[\"'`][^\"'`]*[\"'`]\s*,\s*(?:[\w$.]+\s*,\s*)*([A-Za-z_$][\w$]*)\s*\)", t):
                routes[f].add(m.group(1))
    android_cls = set()
    for f, P in parsed.items():
        for cname, bases, _ in P.get("classes", ()):
            if by_path[f]["lang"] in ("Java", "Kotlin") and _ANDROID_BASE.search(bases or ""):
                android_cls.add((f, cname))
    js_entry_files = set()
    for f, t in texts.items():
        if f.rsplit("/", 1)[-1] == "package.json":
            try:
                j = json.loads(t)
            except ValueError:
                continue
            if not isinstance(j, dict):
                continue
            vals = [j.get("main")] + (list(j["bin"].values()) if isinstance(j.get("bin"), dict) else [j.get("bin")])
            for v in vals:
                if isinstance(v, str):
                    js_entry_files.add(_norm(_dir(f) + "/" + v))
    py_scripts = {}
    for f, t in texts.items():
        if f.endswith("pyproject.toml") or f.endswith("setup.py") or f.endswith("setup.cfg"):
            for m in re.finditer(r"(?m)^\s*[\"']?([\w.-]+)[\"']?\s*=\s*[\"']?([\w.]+):([\w.]+)", t):
                py_scripts[(m.group(2), m.group(3).split(".")[-1])] = m.group(1)
    entries = []
    for i, d in enumerate(defs):
        f = d["file"]
        info = by_path[f]
        if info["role"] != "code":
            continue
        lang, n, kind, label = info["lang"], d["name"], None, None
        base = f.rsplit("/", 1)[-1]
        if lang == "Python":
            if d.get("pseudo") == "main":
                kind = "main"
            elif d.get("pseudo") == "module" and not any(x.get("pseudo") == "main" for x in parsed[f]["defs"]) and (
                    base == "__main__.py" or texts.get(f, "").startswith("#!")):
                kind = "script"
            elif any(re.search(r"(^|\.)(route|get|post|put|delete|patch|websocket|api_route)$", a) for a in d["ann"]):
                kind, label = "http", d.get("route") or None
            elif any(re.search(r"(^|\.)(command|group)$", a) for a in d["ann"]):
                kind = "cli"
            elif n in ("lambda_handler", "handler") and d["params"] == 2 and not d["cls"]:
                kind = "lambda"
            else:
                mod = f[:-3].replace("/", ".")
                for (m_, fn), script in py_scripts.items():
                    if fn == n and (mod == m_ or mod.endswith("." + m_) or mod.endswith(m_.replace(".", "/"))):
                        kind, label = "cli", script
        elif lang in ("C", "C++", "Objective-C"):
            if n in ("main", "wmain", "WinMain", "wWinMain", "_tmain") and not d["cls"]:
                kind = "main"
        elif lang in ("Java", "Kotlin", "Scala", "Groovy"):
            if n == "main" and (lang == "Kotlin" or "static" in d["sig"] or lang == "Scala"):
                kind = "main"
            elif set(d["ann"]) & _HTTP_ANN:
                kind = "http"
            elif n in _ANDROID_HOOKS and (f, d["cls"]) in android_cls:
                kind = "android"
        elif lang == "Go":
            if n == "main" and not d["cls"] and parsed[f].get("pkg") == "main":
                kind = "main"
            elif any(n in routes[g] for g in routes if _dir(g) == _dir(f) or g == f):
                kind = "http"
        elif lang == "Rust":
            if n == "main" and not d["cls"]:
                kind = "main"
        elif lang == "C#":
            if n == "Main" and "static" in d["sig"]:
                kind = "main"
            elif set(d["ann"]) & _HTTP_ANN:
                kind = "http"
        elif lang in ("JavaScript", "TypeScript"):
            if d.get("pseudo") == "module" and (f in js_entry_files or re.match(
                    r"(index|main|server|app|cli)\.[cm]?[jt]sx?$", base) and f.count("/") <= 2):
                kind = "module"
            elif any(n in routes[g] for g in routes if g == f or _dir(g) == _dir(f)):
                kind = "http"
        elif lang in ("Dart", "Swift"):
            if n == "main" and not d["cls"]:
                kind = "main"
        elif lang == "PHP":
            if d.get("pseudo") == "module" and base == "index.php":
                kind = "script"
        if kind:
            entries.append({"i": i, "kind": kind, "label": label})
    srckind = {c["id"]: c["kind"] for c in comps}
    code_by_lang = Counter(i["lang"] for i in infos if i["role"] == "code" for _ in range(max(1, i["lines"] // 50)))
    all_code = sum(code_by_lang.values()) or 1

    def side(i):
        """True for entry points outside the product: tooling, examples, or a minor language of the repo."""
        f = defs[i]["file"]
        return srckind.get(comp_of[f]) not in ("source", "web") or code_by_lang[by_path[f]["lang"]] < 0.1 * all_code

    api = [{"i": i, "kind": "api", "label": None} for i, d in enumerate(defs)
           if not d.get("pseudo") and d["public"] and not called[i] and by_path[d["file"]]["role"] == "code"
           and len(graph[i]) >= 2 and not d["name"].startswith(("_", "~")) and d["name"] != d["cls"]
           and not side(i) and i not in {e["i"] for e in entries}]
    have_main = any(not side(e["i"]) for e in entries)

    def reach(i, limit=400):
        seen, todo = {i}, [i]
        while todo and len(seen) < limit:
            for t, _ in graph[todo.pop()]:
                if t not in seen:
                    seen.add(t)
                    todo.append(t)
        return len(seen) - 1

    for e in entries + api:
        e["reach"] = reach(e["i"])
        e["side"] = side(e["i"])
    api = sorted(api, key=lambda e: (-e["reach"], defs[e["i"]]["file"]))[:12]
    entries.sort(key=lambda e: (e["side"], KIND_ORDER[e["kind"]], -e["reach"], defs[e["i"]]["file"],
                                defs[e["i"]]["line"]))
    entries = [e for e in entries if not e["side"]] + api + [e for e in entries if e["side"]]

    # ---- flows
    chosen = []
    best = max([e["reach"] for e in entries] or [0])
    pool = [e for e in entries if e["reach"] >= min(3, best) and e["reach"] > 0] or entries[:1]
    main_pool = [e for e in pool if not e["side"] and e["kind"] != "api"]
    for group in (main_pool, [e for e in pool if e["kind"] == "api"], [e for e in pool if e["side"]]):
        for kind in sorted(KIND_ORDER, key=KIND_ORDER.get):
            for e in group:
                if e["kind"] == kind and len(chosen) < flows and e not in chosen:
                    chosen.append(e)
                    break
        for e in sorted(group, key=lambda e: -e["reach"]):
            if len(chosen) < flows and e not in chosen:
                chosen.append(e)
    for e in entries:
        if len(chosen) < flows and e not in chosen and e["reach"] > 0:
            chosen.append(e)
    chosen.sort(key=lambda e: (e["side"], KIND_ORDER[e["kind"]], -e["reach"]))
    flow_list = []
    for e in chosen:
        flow_list.append(_make_flow(e, defs, graph, comp_of, cindex, steps))

    # ---- components: externals, actors, HLD selection, layers, tiers
    systems, actors = {}, {}
    for c in comps:
        ext = ext_by_comp.get(c["id"], Counter())
        c["packages"] = [n for n, _ in ext.most_common(8)]
        c["systems"] = []
        for n in (ext if c["kind"] in ("source", "web", "tooling") else ()):
            ms = match_system(n)
            if ms and ms[0] not in c["systems"]:
                c["systems"].append(ms[0])
                s = systems.setdefault(ms[0], {"label": ms[0], "shape": ms[1], "used_by": [], "via": []})
                s["used_by"].append(c["id"])
                if n not in s["via"]:
                    s["via"].append(n)
            if _in(n, SERVERS):
                actors.setdefault("HTTP client", set()).add(c["id"])
            if _in(n, GUIS):
                actors.setdefault("End user (UI)", set()).add(c["id"])
        c["entries"] = []
        c["tested"] = c["id"] in tested
    for e in entries:
        d = defs[e["i"]]
        cid = comp_of[d["file"]]
        cindex[cid]["entries"].append({"name": def_label(d), "file": d["file"], "line": d["line"], "kind": e["kind"]})
        if not e["side"] and (e["kind"] != "api" or not have_main):
            actors.setdefault(ACTORS[e["kind"]], set()).add(cid)
    for c in comps:
        c["entries"] = c["entries"][:8]
    drawable = [c for c in comps if c["kind"] in ("source", "web", "tooling") and c["code_lines"] > 0]
    drawable.sort(key=lambda c: (-(1 if c["entries"] else 0), -c["code_lines"]))
    degree = Counter()
    for (a, b), wgt in edge_w.items():
        degree[a] += wgt
        degree[b] += wgt
    if len(drawable) > 24:
        keep = set(c["id"] for c in drawable if c["entries"][:1])
        rest = sorted((c for c in drawable if c["id"] not in keep),
                      key=lambda c: -(c["code_lines"] ** 0.5 + 20 * degree[c["id"]] ** 0.5))
        keep |= set(c["id"] for c in rest[:max(0, 24 - len(keep))])
        drawable = [c for c in drawable if c["id"] in keep]
    hld = {c["id"] for c in drawable}
    adj = defaultdict(set)
    for (a, b) in edge_w:
        if a in hld and b in hld:
            adj[a].add(b)
    scc = _sccs(sorted(hld), adj)
    rep = {}
    for k, group in enumerate(scc):
        for v in group:
            rep[v] = k
    dag = defaultdict(set)
    indeg = Counter()
    for a in adj:
        for b in adj[a]:
            if rep[a] != rep[b] and rep[b] not in dag[rep[a]]:
                dag[rep[a]].add(rep[b])
                indeg[rep[b]] += 1
    layer = {k: 0 for k in range(len(scc))}
    order = [k for k in range(len(scc)) if not indeg[k]]
    q = list(order)
    while q:
        k = q.pop(0)
        for t in dag[k]:
            layer[t] = max(layer[t], layer[k] + 1)
            indeg[t] -= 1
            if not indeg[t]:
                q.append(t)
    has_edges = any(adj.values())
    for c in comps:
        c["hld"] = c["id"] in hld
        if c["hld"]:
            k = rep[c["id"]]
            c["layer"] = layer[k]
            if not has_edges:
                c["tier"] = 0
            elif layer[k] == 0:
                c["tier"] = 0
            elif not dag[k]:
                c["tier"] = 2
            else:
                c["tier"] = 1
    cycles_all = [g for g in _sccs(sorted(c["id"] for c in comps if c["kind"] != "tests"),
                                   {a: {b for b in comp_deps[a] if cindex[b]["kind"] != "tests"} for a in comp_deps})
                  if len(g) > 1]
    edges = [{"from": a, "to": b, "weight": wgt} for (a, b), wgt in sorted(edge_w.items(), key=lambda kv: (-kv[1], kv[0]))]

    own = set(by_name)
    F.items = [f for f in F.items if not (f["rule"] in ("SEC006", "SEC007", "SEC004", "SEC003") and
                                          re.match(r"[\w.:>-]*?(\w+)\s*\(", f["msg"]) and
                                          re.match(r"[\w.:>-]*?(\w+)\s*\(", f["msg"]).group(1) in own)]
    # ---- deps, commands, global audit
    deps = parse_deps(texts)
    _global_checks(infos, texts, comps, edges, cycles_all, deps, defs, words, used_git, F, by_path)
    stats_langs = Counter()
    for i in infos:
        if i["role"] in ("code", "test") and i["status"] == "read" and i["lang"]:
            stats_langs[i["lang"]] += i["lines"]
    ci = sorted(p for p in paths if is_ci(p))
    model = {
        "engine": ENGINE, "name": title or os.path.basename(os.path.abspath(root)), "source": source or root,
        "root": os.path.abspath(root), "generated": time.strftime("%Y-%m-%d"),
        "listed_with": "git ls-files" if used_git else "folder walk",
        "git": git_facts(root) if used_git else {},
        "stats": {
            "files": len(infos), "read_files": sum(1 for i in infos if i["status"] == "read"),
            "lines": sum(i["lines"] for i in infos if i["status"] == "read"),
            "code_files": sum(1 for i in infos if i["role"] == "code" and i["status"] == "read"),
            "code_lines": sum(i["lines"] for i in infos if i["role"] == "code" and i["status"] == "read"),
            "test_files": sum(1 for i in infos if i["role"] == "test" and i["status"] == "read"),
            "test_lines": sum(i["lines"] for i in infos if i["role"] == "test" and i["status"] == "read"),
            "languages": dict(stats_langs.most_common()),
            "parsed_files": len(parsed), "functions": sum(1 for d in defs if not d.get("pseudo")),
            "calls": total_calls, "calls_resolved": resolved, "seconds": round(time.time() - t0, 2),
        },
        "components": comps, "edges": edges, "cycles": cycles_all,
        "entries": [{"name": def_label(defs[e["i"]]), "file": defs[e["i"]]["file"], "line": defs[e["i"]]["line"],
                     "kind": e["kind"], "label": e["label"], "reach": e["reach"]} for e in entries[:40]],
        "flows": flow_list,
        "systems": sorted(systems.values(), key=lambda s: s["label"]),
        "actors": [{"label": k, "to": sorted(v)} for k, v in sorted(actors.items())],
        "deps": deps[:400], "ci": ci[:20], "commands": find_commands(texts, paths),
        "manifests": sorted(p for p in paths if p.rsplit("/", 1)[-1].lower() in BUILD_NAMES)[:40],
        "findings": sorted(F.items, key=lambda x: (SEV_ORDER[x["sev"]], x["rule"], x["file"], x["line"])),
        "finding_counts": dict(F.counts), "notes": notes[:20],
        "files": [{k: i[k] for k in ("path", "lang", "role", "status", "reason", "lines", "symbols") if i.get(k)
                   or k in ("lines", "reason")} for i in infos],
    }
    for i, info in zip(model["files"], infos):
        i["component"] = comp_of[info["path"]]
        if "peek" in info:
            i["peek"] = info["peek"]
    return model


def _make_flow(e, defs, graph, comp_of, cindex, max_steps, max_depth=6):
    entry = defs[e["i"]]
    # choose calls breadth first (every top-level step before any detail), then list them in call order
    picked, parent, queue, truncated = set(), {e["i"]: None}, [(e["i"], 1)], False
    while queue:
        i, depth = queue.pop(0)
        for t, line in graph[i]:
            if len(picked) >= max_steps:
                truncated = True
                break
            picked.add((i, t, line))
            if t not in parent and depth < max_depth:
                parent[t] = i
                queue.append((t, depth + 1))
        if truncated:
            break
    raw = []

    def visit(i, depth):
        for t, line in graph[i]:
            if (i, t, line) in picked:
                raw.append((depth, i, t, line))
                if parent.get(t) == i:
                    visit(t, depth + 1)

    visit(e["i"], 1)
    files = {defs[x]["file"] for _, a, b, _ in raw for x in (a, b)} | {entry["file"]}
    by_comp = len({comp_of[f] for f in files}) > 1
    key = (lambda f: comp_of[f]) if by_comp else (lambda f: f)
    order = []
    for f in [entry["file"]] + [defs[x]["file"] for _, a, b, _ in raw for x in (a, b)]:
        if key(f) not in order:
            order.append(key(f))
    if len(order) > 8:
        order = order[:7] + ["(other)"]
    pidx = {k: n for n, k in enumerate(order)}

    def p_of(f):
        return pidx.get(key(f), len(order) - 1)

    def plabel(k):
        if k == "(other)":
            return "other components"
        if by_comp:
            return cindex[k]["name"] if k in cindex else (k or "(root)")
        return k.rsplit("/", 1)[-1]

    steps = [{"n": n + 2, "depth": dep, "from": p_of(defs[a]["file"]), "to": p_of(defs[b]["file"]),
              "call": def_label(defs[b]), "file": defs[b]["file"], "line": defs[b]["line"],
              "at": "%s:%d" % (defs[a]["file"], line)} for n, (dep, a, b, line) in enumerate(raw)]
    title = (e.get("label") + ": " if e.get("label") else "") + def_label(entry) + " in " + entry["file"]
    return {"key": "%s:%s" % (entry["file"], def_label(entry)), "kind": e["kind"], "title": title,
            "actor": ACTORS[e["kind"]], "entry": {"label": def_label(entry), "file": entry["file"],
                                                  "line": entry["line"], "p": p_of(entry["file"])},
            "participants": [{"key": k, "label": plabel(k)} for k in order], "steps": steps,
            "truncated": truncated, "reach": e["reach"]}


def _global_checks(infos, texts, comps, edges, cycles, deps, defs, words, used_git, F, by_path):
    root_files = {i["path"].lower(): i for i in infos if "/" not in i["path"]}
    readme = next((i for p, i in root_files.items() if p.startswith("readme")), None)
    code_lines = sum(i["lines"] for i in infos if i["role"] == "code" and i["status"] == "read")
    if not readme:
        F.add("DOC001", "", 0, "no README in the repository root")
    else:
        t = texts.get(readme["path"], "")
        if len(t.strip()) < 400:
            F.add("DOC002", readme["path"], 1, "%d characters" % len(t.strip()))
        if t and not re.search(r"(?im)^#+\s*.*\b(install|installation|build|building|usage|getting started|quick ?start"
                               r"|run|running|setup|how to|develop|compil)", t) and "```" not in t:
            F.add("DOC004", readme["path"], 1, "")
    if not any(p.startswith(("license", "licence", "copying", "unlicense")) for p in root_files):
        F.add("DOC003", "", 0, "no LICENSE or COPYING file in the root")
    tests = [i for i in infos if i["role"] == "test" and i["status"] == "read" and i["lang"] in CODE_LANGS]
    test_lines = sum(i["lines"] for i in tests)
    if code_lines >= 200 and not tests:
        F.add("TST001", "", 0, "no test files found")
    elif code_lines >= 1000 and test_lines < 0.1 * code_lines:
        F.add("TST002", "", 0, "%d test lines for %d code lines (%.0f%%)" % (test_lines, code_lines,
                                                                           100.0 * test_lines / code_lines))
    if tests:
        test_names = " ".join(i["path"].lower() for i in tests)
        for c in comps:
            if c["kind"] == "source" and c["code_lines"] >= 300 and not c.get("tested") and not c["test_lines"] \
                    and c["name"].lower().rsplit(".", 1)[0] not in test_names:
                F.add("TST003", c["id"] or "(root)", 0, "%s: %d code lines, no test imports it" % (c["name"],
                                                                                                c["code_lines"]))
    paths = [i["path"] for i in infos]
    if code_lines >= 200 and not any(is_ci(p) for p in paths):
        F.add("BLD001", "", 0, "no CI workflow found")
    names = {p.rsplit("/", 1)[-1].lower() for p in paths}
    langs = Counter(i["lang"] for i in infos if i["role"] == "code")
    need = [("Python", ("pyproject.toml", "setup.py", "setup.cfg", "pipfile"), ("requirements",)),
            ("JavaScript", ("package.json", "deno.json"), ()), ("TypeScript", ("package.json", "deno.json"), ()),
            ("Go", ("go.mod",), ()), ("Rust", ("cargo.toml",), ()),
            ("Java", ("pom.xml", "build.gradle", "build.gradle.kts", "build.xml"), ()),
            ("Kotlin", ("build.gradle", "build.gradle.kts", "pom.xml"), ()),
            ("C", ("makefile", "cmakelists.txt", "meson.build", "configure.ac", "build.bazel", "build"), ("make",)),
            ("C++", ("makefile", "cmakelists.txt", "meson.build", "configure.ac", "build.bazel", "build"), ("make",)),
            ("C#", (), (".csproj", ".sln"))]
    for lang, exact, partial in need:
        if langs[lang] >= 3 and not (names & set(exact)) and not any(n.startswith(partial) or n.endswith(partial)
                                                                    for n in names for _ in [0] if partial):
            F.add("BLD002", "", 0, "%s code but no %s" % (lang, " / ".join(exact or partial)))
    for d in deps:
        st = _pin_state(d)
        if st == "wild":
            F.add("DEP003", d["file"], d["line"], "%s %s" % (d["name"], d["spec"] or "(empty)"))
        elif st == "none" and not d["dev"]:
            F.add("DEP001", d["file"], d["line"], d["name"])
    lower_paths = {p.lower() for p in paths}

    def has_lock(d, locks):
        return any((d + "/" + l if d else l) in lower_paths for l in locks)

    for f in sorted({d["file"] for d in deps}):
        low, d = f.rsplit("/", 1)[-1].lower(), _dir(f).lower()
        if low == "package.json" and any(x["file"] == f and not x["dev"] for x in deps) and not has_lock(
                d, ("package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "npm-shrinkwrap.json")) \
                and not has_lock("", ("package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb")):
            F.add("DEP002", f, 0, "npm: no package-lock.json, yarn.lock or pnpm-lock.yaml")
        elif low == "pyproject.toml" and any(x["eco"] == "poetry" and x["file"] == f for x in deps) \
                and not has_lock(d, ("poetry.lock",)):
            F.add("DEP002", f, 0, "poetry: no poetry.lock")
        elif low == "cargo.toml" and ((d + "/src/main.rs").lstrip("/") in lower_paths) and not has_lock(d, ("cargo.lock",)) \
                and not has_lock("", ("cargo.lock",)):
            F.add("DEP002", f, 0, "cargo application: no Cargo.lock")
        elif low == "go.mod" and any(x["file"] == f for x in deps) and not has_lock(d, ("go.sum",)):
            F.add("DEP002", f, 0, "go: no go.sum")
        elif low in ("gemfile", "composer.json") and not has_lock(d, ("gemfile.lock", "composer.lock")):
            F.add("DEP002", f, 0, "no lock file next to it")
    cindex = {c["id"]: c for c in comps}
    for g in cycles:
        F.add("DES001", g[0] or "(root)", 0, " <-> ".join(cindex[x]["name"] for x in g[:6]))
    src = [c for c in comps if c["kind"] in ("source", "web")]
    total = sum(c["code_lines"] for c in src) or 1
    fan_out = Counter(e["from"] for e in edges)
    for c in src:
        if len(src) >= 4 and c["code_lines"] / total > 0.5:
            F.add("DES002", c["id"] or "(root)", 0, "%s holds %.0f%% of the code" % (c["name"],
                                                                                 100.0 * c["code_lines"] / total))
        elif fan_out[c["id"]] >= 8:
            F.add("DES002", c["id"] or "(root)", 0, "%s imports %d other components" % (c["name"], fan_out[c["id"]]))
    for d in defs:
        if d.get("pseudo") or by_path[d["file"]]["role"] != "code":
            continue
        n = d["end"] - d["line"] + 1
        if n > 100:
            F.add("COD002", d["file"], d["line"], "%s: %d lines" % (def_label(d), n))
        limit = 4 if by_path[d["file"]]["lang"] == "Python" else 6
        if d["nest"] > limit:
            F.add("COD003", d["file"], d["line"], "%s: %d levels" % (def_label(d), d["nest"]))
        if d["params"] > 7:
            F.add("COD006", d["file"], d["line"], "%s: %d parameters" % (def_label(d), d["params"]))
        nm = d["name"]
        if not d["public"] and words[nm] <= 1 and not d["ann"] and not nm.startswith("__") \
                and nm not in ("main", "init", "setUp", "tearDown"):
            F.add("DES003", d["file"], d["line"], def_label(d))
    if used_git and not any(p == ".gitignore" for p in paths):
        F.add("HYG001", "", 0, "no .gitignore in the root")
    if used_git:
        out_rx = re.compile(r"(^|/)(node_modules|__pycache__|\.gradle|target/classes|bin/Debug|bin/Release|obj/Debug|"
                            r"obj/Release|\.pytest_cache|\.mypy_cache|\.venv|venv)/|\.(pyc|pyo|class|o|obj|so|dll|"
                            r"dylib|exe)$")
        hits = [p for p in paths if out_rx.search(p) and not p.endswith(("gradle-wrapper.jar",))]
        for p in hits[:20]:
            F.add("HYG002", p, 0, "")
    for i in infos:
        if i["size"] > MAX_BYTES:
            F.add("HYG003", i["path"], 0, "%.1f MB" % (i["size"] / 1048576.0))
        if i["reason"] == "sensitive":
            F.add("SEC002", i["path"], 0, "not opened; check whether it holds a private key or password",
                  i["role"] == "test")


# ============================================================================ health score

def dismissed_by(f, dismissed):
    if not dismissed:
        return None
    for key in ("%s@%s:%s" % (f["rule"], f["file"], f["line"]), "%s@%s" % (f["rule"], f["file"]), f["rule"]):
        if key in dismissed:
            return dismissed[key]
    return None


def health(model, dismissed=None):
    """Score 0-100 per area and overall, with the active (not dismissed) findings."""
    active, gone = [], []
    for f in model["findings"]:
        (gone if dismissed_by(f, dismissed) is not None else active).append(f)
    groups = defaultdict(list)
    for f in active:
        groups[(f["rule"], f["sev"])].append(f)
    pen = Counter()
    for (rule, sev), fs in groups.items():
        area, base_sev, _, _, p = RULES[rule]
        w = p if (p and sev == base_sev) else SEV_W[sev]
        if all(f["msg"].endswith("(test code)") for f in fs):
            w *= 0.5
        pen[area] += w * min(2.0, 1 + 0.25 * (len(fs) - 1))
    areas = {k: max(0, int(round(100 - pen[k]))) for k, _, _ in AREAS}
    score = int(round(sum(areas[k] * w for k, _, w in AREAS) / float(sum(w for _, _, w in AREAS))))
    grade = "A" if score >= 90 else "B" if score >= 80 else "C" if score >= 70 else "D" if score >= 60 else "F"
    sev = Counter(f["sev"] for f in active)
    return {"score": score, "grade": grade, "areas": areas, "active": active, "dismissed": gone, "groups": groups,
            "sev": sev}


# ============================================================================ rendering (Mermaid + Markdown)

def fmt(n):
    return "{:,}".format(n)


def kfmt(n):
    return "%.1fk" % (n / 1000.0) if n >= 1000 else str(n)


def md_cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


_MM = {"#": "#35;", '"': "#quot;", "<": "#lt;", ">": "#gt;"}
_MM_SEQ = dict(_MM, **{";": "#59;", ":": "#58;", "\n": " "})


def mm(s):
    """Text inside a quoted Mermaid label."""
    return re.sub(r'[#"<>]', lambda m: _MM[m.group()], str(s))


def mm_seq(s):
    """Text in a sequence diagram name or message."""
    return re.sub(r'[#"<>;:\n]', lambda m: _MM_SEQ[m.group()], str(s))


TIERS = ["Entry points & apps", "Core logic", "Foundation & shared"]
SHAPES = {"db": '[("%s")]', "queue": '[/"%s"/]', "api": '{{"%s"}}', "cloud": '(["%s"])', "platform": '[["%s"]]'}
CLASSDEFS = [
    "classDef actor fill:#fff7e6,stroke:#d48806,color:#613400",
    "classDef entry fill:#e6f0ff,stroke:#2f6fdb,color:#0b2a5b",
    "classDef core fill:#e8f7ef,stroke:#2e9d63,color:#0d3b24",
    "classDef base fill:#f2f2f2,stroke:#7a7a7a,color:#262626",
    "classDef web fill:#f3e8ff,stroke:#8b5cf6,color:#3b0764",
    "classDef tool fill:#fff1e6,stroke:#e8792b,color:#5c2a05",
    "classDef ext fill:#ffffff,stroke:#9aa5b1,color:#1f2933,stroke-dasharray:4 3",
]


def hld_mermaid(model, titles=None, max_edges=40):
    """High-level design: actors, components in tiers, external systems."""
    titles = titles or {}
    nodes = [c for c in model["components"] if c.get("hld")]
    if not nodes:
        return ""
    ids = {c["id"]: "C%d" % k for k, c in enumerate(nodes)}
    L = ["flowchart TB"]
    for k, a in enumerate(model["actors"]):
        if any(t in ids for t in a["to"]):
            L.append('    A%d(["%s"]):::actor' % (k, mm(a["label"])))
    tiers = sorted({c["tier"] for c in nodes})
    for t in tiers:
        title = TIERS[t] if len(tiers) > 1 else "Components"
        L += ['    subgraph T%d["%s"]' % (t, title), "        direction LR"]
        for c in sorted((c for c in nodes if c["tier"] == t), key=lambda c: (-c["code_lines"], c["id"])):
            lang = next(iter(c["langs"]), "")
            detail = titles.get(c["id"]) or " &middot; ".join(x for x in (lang, kfmt(c["code_lines"]) + " lines") if x)
            cls = "web" if c["kind"] == "web" else "tool" if c["kind"] == "tooling" else ["entry", "core", "base"][t]
            L.append('        %s["<b>%s</b><br/>%s"]:::%s' % (ids[c["id"]], mm(c["name"]), mm(detail)
                                                         .replace("#amp;middot;", "&middot;"), cls))
        L.append("    end")
    used = [s for s in model["systems"] if any(u in ids for u in s["used_by"])]
    if used:
        L += ['    subgraph EXT["External systems"]', "        direction LR"]
        for k, s in enumerate(used):
            L.append("        X%d%s:::ext" % (k, SHAPES.get(s["shape"], '["%s"]') % mm(s["label"])))
        L.append("    end")
    for k, a in enumerate(model["actors"]):
        for t in a["to"]:
            if t in ids:
                L.append("    A%d --> %s" % (k, ids[t]))
    cyc = {x for g in model.get("cycles", []) for x in g}
    edges = [e for e in model["edges"] if e["from"] in ids and e["to"] in ids][:max_edges]
    heavy = sorted((e["weight"] for e in edges), reverse=True)
    thr = max(5, heavy[len(heavy) // 4] if heavy else 5)
    for e in edges:
        arrow = "-.->" if e["from"] in cyc and e["to"] in cyc else "==>" if e["weight"] >= thr else "-->"
        L.append("    %s %s %s" % (ids[e["from"]], arrow, ids[e["to"]]))
    for k, s in enumerate(used):
        for u in s["used_by"]:
            if u in ids:
                L.append("    %s -.-> X%d" % (ids[u], k))
    L += ["    " + c for c in CLASSDEFS]
    return "\n".join(L).replace("&amp;middot;", "&middot;")


def flow_mermaid(flow):
    L = ["sequenceDiagram", "    autonumber", "    actor U as %s" % mm_seq(flow["actor"])]
    for k, p in enumerate(flow["participants"]):
        L.append("    participant P%d as %s" % (k, mm_seq(p["label"])))
    L.append("    U->>P%d: %s" % (flow["entry"]["p"], mm_seq(flow["entry"]["label"])))
    for s in flow["steps"]:
        L.append("    P%d->>P%d: %s" % (s["from"], s["to"], mm_seq(s["call"])))
    if flow.get("truncated"):
        L.append("    Note over P%d: more calls not shown" % flow["entry"]["p"])
    return "\n".join(L)


def flow_table(flow):
    L = ["| # | Call | Defined in | Called from |", "|---|---|---|---|",
         "| 1 | `%s` | `%s:%d` | %s |" % (md_cell(flow["entry"]["label"]), flow["entry"]["file"], flow["entry"]["line"],
                                         md_cell(flow["actor"]))]
    for s in flow["steps"]:
        L.append("| %d | %s`%s` | `%s:%d` | `%s` |" % (s["n"], "&nbsp;&nbsp;" * (s["depth"] - 1) + "&#8627; ",
                                                     md_cell(s["call"]), s["file"], s["line"], s["at"]))
    return "\n".join(L)


def glance_md(model, h):
    st = model["stats"]
    g = model.get("git", {})
    langs = ", ".join("%s %s" % (l, kfmt(n)) for l, n in list(st["languages"].items())[:6]) or "none"
    L = ["| | |", "|---|---|",
         "| Source | %s%s |" % (md_cell(g.get("remote") or model["source"]), (" @ %s (%s)" % (g["head"], g.get("branch", "?"))
                                                                   if g.get("head") else "")),
         "| Files | %s (%s read), %s lines |" % (fmt(st["files"]), fmt(st["read_files"]), fmt(st["lines"])),
         "| Code | %s files, %s lines; tests: %s files, %s lines |" % (fmt(st["code_files"]), fmt(st["code_lines"]),
                                                                    fmt(st["test_files"]), fmt(st["test_lines"])),
         "| Languages (lines) | %s |" % langs,
         "| Components | %d (%d in the diagram) |" % (len(model["components"]),
                                                     sum(1 for c in model["components"] if c.get("hld"))),
         "| Functions | %s parsed, %s of %s calls resolved inside the repo |" % (
             fmt(st["functions"]), fmt(st["calls_resolved"]), fmt(st["calls"])),
         "| Entry points | %d |" % len(model["entries"]),
         "| External systems | %s |" % (", ".join(s["label"] for s in model["systems"]) or "none detected"),
         "| Health score | **%d/100 (%s)** |" % (h["score"], h["grade"])]
    return "\n".join(L)


def audit_md(model, dismissed=None, heading="##"):
    h = health(model, dismissed)
    sub = heading + "#"
    L = [heading + " Health audit", "",
         "**Score: %d/100, grade %s.** %d high, %d medium, %d low findings%s. Each area starts at 100 and loses "
         "points per rule found (more for high severity, a little more for each repeat)." % (
             h["score"], h["grade"], h["sev"]["HIGH"], h["sev"]["MEDIUM"], h["sev"]["LOW"],
             ", %d dismissed" % len(h["dismissed"]) if h["dismissed"] else ""), "",
         "| Area | Score | Weight |", "|---|---|---|"]
    for k, title, w in AREAS:
        L.append("| %s | %d | %d%% |" % (title, h["areas"][k], w))
    if h["groups"]:
        L += ["", sub + " Findings", "", "| Severity | Area | Rule | Count | Where | Fix |", "|---|---|---|---|---|---|"]
        rows = sorted(h["groups"].items(), key=lambda kv: (SEV_ORDER[kv[0][1]], -len(kv[1]), kv[0][0]))
        area_title = {k: t for k, t, _ in AREAS}
        for (rule, sev), fs in rows:
            area, _, title, fix, _ = RULES[rule]
            total = model["finding_counts"].get(rule, len(fs)) if len(fs) >= Findings.CAP else len(fs)
            where = ", ".join("`%s%s`" % (f["file"] or "(repo)", ":%d" % f["line"] if f["line"] else "")
                              for f in fs[:3]) + (" ..." if len(fs) > 3 else "")
            L.append("| %s | %s | %s %s | %d | %s | %s |" % (sev, area_title[area], rule, title, total, where,
                                                             md_cell(fix)))
        L += ["", "<details><summary>Every finding (%d)</summary>" % len(h["active"]), ""]
        for f in sorted(h["active"], key=lambda f: (SEV_ORDER[f["sev"]], f["rule"], f["file"], f["line"]))[:400]:
            loc = (f["file"] or "(repo)") + (":%d" % f["line"] if f["line"] else "")
            L.append("- %s %s `%s` %s" % (f["sev"], f["rule"], loc, md_cell(f["msg"])))
        L += ["", "</details>"]
    if h["dismissed"]:
        L += ["", sub + " Dismissed after review", ""]
        for f in h["dismissed"][:50]:
            L.append("- %s `%s%s`: %s" % (f["rule"], f["file"] or "(repo)", ":%d" % f["line"] if f["line"] else "",
                                          md_cell(dismissed_by(f, dismissed))))
    L += ["", "Findings come from static patterns: confirm each one in the code before acting on it."]
    return "\n".join(L)


