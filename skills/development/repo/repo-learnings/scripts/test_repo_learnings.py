def make_repo(files=REPO):
    d = tempfile.mkdtemp(prefix="rl-test-")
    for rel, data in files.items():
        p = os.path.join(d, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data if isinstance(data, bytes) else data.encode("utf-8"))
    return d


def run(*argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            code = rl.main(list(argv))
        except SystemExit as e:
            code = e.code if isinstance(e.code, int) else 2
            err.write(str(e))
    return code, out.getvalue(), err.getvalue()


class ScanTests(unittest.TestCase):
    def setUp(self):
        self.repo = make_repo()
        self.tmp = tempfile.mkdtemp(prefix="rl-out-")
        self.out = os.path.join(self.tmp, "shop")
        self.code, self.stdout, self.stderr = run("scan", self.repo, "--out", self.out, "--batch-lines", "60")

    def tearDown(self):
        shutil.rmtree(self.repo, ignore_errors=True)
        shutil.rmtree(self.tmp, ignore_errors=True)

    def files(self):
        return {f["path"]: f for f in rm.load_json(os.path.join(self.out, rl.MANIFEST))["files"]}

    def learnings(self):
        with io.open(os.path.join(self.out, rl.LEARNINGS), encoding="utf-8") as f:
            return f.read()

    def test_scan_writes_outputs(self):
        self.assertEqual(self.code, 0, self.stderr)
        for name in (rl.MANIFEST, rl.MODEL, rl.PLAN, rl.LEARNINGS):
            self.assertTrue(os.path.exists(os.path.join(self.out, name)), name)
        self.assertIn("health", self.stdout)

    def test_classification(self):
        f = self.files()
        self.assertEqual((f["src/app/main.py"]["status"], f["src/app/main.py"]["lines"]), ("read", 6))
        self.assertEqual(f["src/app/main.py"]["symbols"], ["main()"])
        for path, reason in (("logo.png", "binary"), ("blob.xyz", "binary"), (".env", "sensitive"),
                             ("deploy/server.pem", "sensitive"), ("package-lock.json", "lockfile"),
                             ("vendor/lib/x.go", "vendored"), ("empty.txt", "empty"), ("web/app.min.js", "minified")):
            self.assertEqual((f[path]["status"], f[path]["reason"]), ("skip", reason), path)
        self.assertEqual(f[".env.example"]["status"], "read")
        self.assertEqual((f["gen/api_pb2.py"]["status"], f["data/big.csv"]["status"]), ("peek", "peek"))

    def test_learnings_has_diagrams_and_audit(self):
        text = self.learnings()
        self.assertIn("```mermaid\nflowchart TB", text)
        self.assertIn("```mermaid\nsequenceDiagram", text)
        self.assertIn("Cart.Add()", text)
        self.assertIn("### Health audit", text)
        self.assertIn("`make build`", text)
        self.assertGreater(text.count(rl.TODO), 5)

    def test_reading_order_and_batches(self):
        m = rm.load_json(os.path.join(self.out, rl.MANIFEST))
        order = [e["path"] for b in m["batches"] for e in b]
        self.assertEqual(order[0], "README.md")
        self.assertLess(order.index("Makefile"), order.index("cmd/shop/main.go"))
        self.assertLess(order.index("cmd/shop/main.go"), order.index("internal/cart/cart_test.go"))
        self.assertTrue(all(sum(e["end"] - e["start"] + 1 for e in b) <= 60 or len(b) == 1 for b in m["batches"]))

    def test_full_workflow_to_complete(self):
        m = rm.load_json(os.path.join(self.out, rl.MANIFEST))
        code, out, _ = run("next", self.out)
        self.assertIn("Batch 001", out)
        for i, b in enumerate(m["batches"], 1):
            with io.open(rl.notes_path(self.out, i), "w", encoding="utf-8") as f:
                f.write("\n\n".join("### %s\n\n- **Role:** test." % e["path"] for e in b))
        self.assertIn("All %d batches have notes" % len(m["batches"]), run("next", self.out)[1])
        self.assertEqual(run("coverage", self.out)[0], 1)
        path = os.path.join(self.out, rl.LEARNINGS)
        rm.write_text(path, self.learnings().replace(rl.TODO, "Written."))
        self.assertEqual(run("assemble", self.out)[0], 0)
        code, out, _ = run("coverage", self.out)
        self.assertEqual(code, 0, out)
        self.assertIn("Result: complete", out)

    def test_rescan_keeps_text_and_refreshes_auto_blocks(self):
        path = os.path.join(self.out, rl.LEARNINGS)
        text = self.learnings().replace(rl.TODO + ": what it does", "MY OWN WORDS", 1)
        text = text.replace("<!-- auto:health -->", "<!-- auto:health -->\nSTALE", 1)
        rm.write_text(path, text)
        code, out, _ = run("scan", self.repo, "--out", self.out)
        self.assertEqual(code, 0)
        self.assertIn("kept your text", out)
        new = self.learnings()
        self.assertIn("MY OWN WORDS", new)
        self.assertNotIn("STALE", new)
        run("scan", self.repo, "--out", self.out, "--force")
        self.assertNotIn("MY OWN WORDS", self.learnings())

    def test_only_and_include(self):
        out = os.path.join(self.tmp, "only")
        run("scan", self.repo, "--out", out, "--only", "internal", "--include", "data/big.csv")
        paths = {f["path"] for f in rm.load_json(os.path.join(out, rl.MANIFEST))["files"]}
        self.assertEqual(paths, {"internal/cart/cart.go", "internal/cart/cart_test.go"})
        out = os.path.join(self.tmp, "inc")
        run("scan", self.repo, "--out", out, "--include", "data/big.csv")
        f = {x["path"]: x for x in rm.load_json(os.path.join(out, rl.MANIFEST))["files"]}
        self.assertEqual(f["data/big.csv"]["status"], "read")

    def test_errors(self):
        code, _, err = run("scan", os.path.join(self.tmp, "nope"), "--out", os.path.join(self.tmp, "x"))
        self.assertNotEqual(code, 0)
        self.assertIn("not a folder or a git URL", err)
        self.assertEqual(run("next", os.path.join(self.tmp, "none"))[0], 2)
        self.assertEqual(run("batch", self.out, "999")[0], 2)


