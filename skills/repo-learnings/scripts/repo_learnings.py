def repo_name(src):
    name = re.sub(r"\.git$", "", src.rstrip("/\\").replace("\\", "/").rsplit("/", 1)[-1].rsplit(":", 1)[-1])
    return re.sub(r"[^A-Za-z0-9._-]+", "-", name) or "repo"


def build_manifest(root, name, out_dir=None, only=(), exclude=(), include=(), batch_lines=1200, use_git=True):
    paths, used_git = list_files(root, use_git)
    if out_dir:
        try:
            rel_out = os.path.relpath(os.path.abspath(out_dir), root).replace(os.sep, "/")
        except ValueError:
            rel_out = ".."
        if not rel_out.startswith(".."):
            paths = [p for p in paths if not (p == rel_out or p.startswith(rel_out + "/") or rel_out == ".")]
    paths = select(paths, list(only), list(exclude))
    files = []
    for rel in paths:
        info = classify(root, rel)
        if include and info["status"] != "read" and info["reason"] not in ("binary", "symlink", "empty") \
                and any(fnmatch.fnmatch(rel, g) for g in include) and info["lines"]:
            info.update(status="read", reason="")
            info.pop("peek", None)
        files.append(info)
    ordered = sorted((f for f in files if f["status"] in ("read", "peek")),
                     key=lambda f: (reading_priority(f["path"]), f["path"].count("/") == 0 and -1 or 0,
                                    f["path"].lower()))
    batches = make_batches(ordered, batch_lines)
    langs = {}
    for f in files:
        if f["status"] == "read":
            l = langs.setdefault(f["lang"], {"files": 0, "lines": 0})
            l["files"] += 1
            l["lines"] += f["lines"]
    skipped = {}
    for f in files:
        if f["status"] == "skip":
            skipped[f["reason"]] = skipped.get(f["reason"], 0) + 1
    return {
        "name": name,
        "root": os.path.abspath(root),
        "listed_with": "git ls-files" if used_git else "folder walk",
        "git": git_facts(root) if used_git else {},
        "batch_lines": batch_lines,
        "totals": {
            "files": len(files),
            "read_files": sum(1 for f in files if f["status"] == "read"),
            "peek_files": sum(1 for f in files if f["status"] == "peek"),
            "skipped_files": sum(1 for f in files if f["status"] == "skip"),
            "read_lines": sum(f["lines"] for f in files if f["status"] == "read"),
            "batches": len(batches),
        },
        "languages": langs,
        "not_read": skipped,
        "folders": folder_table(files),
        "files": files,
        "batches": batches,
    }


def fmt(n):
    return "{:,}".format(n)


def batch_lines_md(batch, checkbox=True):
    out = []
    for e in batch:
        rng = "lines %d-%d of %d" % (e["start"], e["end"], e["of"]) if (e["start"] > 1 or e["end"] < e["of"]) \
            else ("%d lines" % e["of"])
        tag = " (generated or data: first lines only)" if e["peek"] else ""
        out.append("%s`%s`: %s%s" % ("- [ ] " if checkbox else "- ", e["path"], rng, tag))
    return out


def render_plan(m):
    t = m["totals"]
    L = ["# Reading plan: %s" % m["name"], "",
         "%s files listed with %s. To read: %s files, %s lines, in %d batches of about %s lines. "
         "First lines only: %d files. Not read: %d files." % (
             fmt(t["files"]), m["listed_with"], fmt(t["read_files"]), fmt(t["read_lines"]), t["batches"],
             fmt(m["batch_lines"]), t["peek_files"], t["skipped_files"]), "",
         "Read the batches in order. For each batch, read every listed line range, then write "
         "`%s/batch-NNN.md` with one `### path` heading per file." % NOTES_DIR, ""]
    for i, b in enumerate(m["batches"], 1):
        L += ["## Batch %03d (%s lines)" % (i, fmt(sum(e["end"] - e["start"] + 1 for e in b))), ""]
        L += batch_lines_md(b) + [""]
    skipped = [f for f in m["files"] if f["status"] == "skip"]
    if skipped:
        L += ["## Not read", "", "| Reason | Files | Examples |", "|---|---|---|"]
        by = {}
        for f in skipped:
            by.setdefault(f["reason"], []).append(f["path"])
        for reason in sorted(by):
            ex = ", ".join("`%s`" % p for p in by[reason][:5]) + (" ..." if len(by[reason]) > 5 else "")
            L.append("| %s | %d | %s |" % (reason, len(by[reason]), ex))
        L += ["", "The full list is in `%s`. Files marked sensitive must not be opened or quoted." % MANIFEST, ""]
    return "\n".join(L).rstrip() + "\n"


