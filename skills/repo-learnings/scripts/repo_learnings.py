def run_git(root, *args, **kw):
    try:
        p = subprocess.run(["git", "-C", root] + list(args), stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, timeout=kw.get("timeout", 60))
    except (OSError, subprocess.SubprocessError):
        return None
    if p.returncode != 0:
        return None
    return p.stdout.decode("utf-8", "replace")


def is_git_root(root):
    top = run_git(root, "rev-parse", "--show-toplevel")
    if not top:
        return False
    try:
        return os.path.samefile(top.strip(), root)
    except OSError:
        return False


def list_files(root, use_git=True):
    """Return (sorted relative posix paths, used_git)."""
    if use_git and is_git_root(root):
        out = run_git(root, "-c", "core.quotepath=off", "ls-files", "-co", "--exclude-standard", "-z")
        if out is not None:
            return sorted(set(p for p in out.split("\0") if p)), True
    found = []
    for base, dirs, files in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in HARD_SKIP_DIRS)
        for name in files:
            rel = os.path.relpath(os.path.join(base, name), root).replace(os.sep, "/")
            found.append(rel)
    return sorted(found), False


def any_glob(name, globs):
    return any(fnmatch.fnmatch(name, g) for g in globs)


def is_sensitive(name):
    low = name.lower()
    if low.endswith(SENSITIVE_SAFE_SUFFIX):
        return False
    return low in SENSITIVE_NAMES or any_glob(low, SENSITIVE_GLOBS)


def language_of(name):
    low = name.lower()
    if low in SPECIAL_NAMES:
        return SPECIAL_NAMES[low]
    if low.startswith("dockerfile"):
        return "Dockerfile"
    ext = low.rsplit(".", 1)[1] if "." in low else ""
    return LANG.get(ext, ext.upper() if ext else "Other")


def decode(data):
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return data.decode("utf-16", "replace")
    if data[:3] == b"\xef\xbb\xbf":
        data = data[3:]
    return data.decode("utf-8", "replace")


def classify(root, rel, max_bytes=5 * 1024 * 1024, data_lines=400):
    """Describe one file: status is 'read', 'peek' (first lines only) or 'skip'."""
    path = os.path.join(root, rel)
    name = rel.rsplit("/", 1)[-1]
    low = name.lower()
    ext = low.rsplit(".", 1)[1] if "." in low else ""
    info = {"path": rel, "status": "skip", "reason": "", "lines": 0, "size": 0, "lang": language_of(name)}
    if os.path.islink(path):
        info["reason"] = "symlink"
        return info
    if not os.path.isfile(path):
        info["reason"] = "not a file (submodule or missing)"
        return info
    info["size"] = os.path.getsize(path)
    if is_sensitive(name):
        info["reason"] = "sensitive"
        return info
    if ext in BINARY_EXT:
        info["reason"] = "binary"
        return info
    if info["size"] > max_bytes:
        info["reason"] = "too large"
        return info
    with io.open(path, "rb") as f:
        data = f.read()
    if data[:2] not in (b"\xff\xfe", b"\xfe\xff") and b"\0" in data[:8192]:
        info["reason"] = "binary"
        return info
    text = decode(data)
    lines = text.splitlines()
    info["lines"] = len(lines)
    if not text.strip():
        info["reason"] = "empty"
        return info
    parts = rel.split("/")[:-1]
    if any(p in VENDORED_DIRS for p in parts):
        info["reason"] = "vendored"
        return info
    if low in LOCKFILES or low.endswith(".lock"):
        info["reason"] = "lockfile"
        return info
    longest = max(len(l) for l in lines)
    if ext in ("js", "css", "json", "html") and longest > 2000 and info["size"] / max(len(lines), 1) > 300:
        info["reason"] = "minified"
        return info
    if any_glob(low, GENERATED_GLOBS) or GENERATED_MARK.search("\n".join(lines[:5])):
        info.update(status="peek", reason="generated", peek=min(len(lines), 40))
        return info
    if ext in DATA_EXT and len(lines) > data_lines and info["lang"] not in ("Markdown",):
        info.update(status="peek", reason="large data file", peek=60)
        return info
    info["status"] = "read"
    if info["lang"] in CODE_LANGS:
        seen = []
        for line in lines:
            m = SYMBOL.match(line)
            if m and m.group(1) not in seen:
                seen.append(m.group(1))
                if len(seen) >= 60:
                    break
        if seen:
            info["symbols"] = seen
    return info


def reading_priority(rel):
    """Lower comes first: orientation, build files, docs, entry points, source, tests, the rest."""
    parts = rel.split("/")
    name = parts[-1].lower()
    stem = name.split(".", 1)[0]
    depth = len(parts) - 1
    lowparts = [p.lower() for p in parts[:-1]]
    if depth == 0 and stem == "readme":
        return 0
    if depth == 0 and stem in DOC_NAMES:
        return 1
    if name in MANIFEST_NAMES or name.startswith("requirements") or name.startswith("dockerfile") \
            or ".github" in lowparts or name.endswith((".csproj", ".sln")):
        return 2
    if lowparts and lowparts[0] in ("docs", "doc", "documentation") or (stem == "readme"):
        return 3
    is_test = any(p in ("test", "tests", "__tests__", "spec", "specs", "androidtest", "e2e", "fixtures",
                        "testdata") for p in lowparts) \
        or name.startswith("test_") or re.search(r"(_test|\.test|\.spec|test)\.[a-z0-9]+$", name) is not None
    if is_test:
        return 6
    lang = language_of(parts[-1])
    if lang in CODE_LANGS:
        return 4 if stem in ENTRY_STEMS else 5
    return 7


def select(paths, only, exclude):
    out = []
    for p in paths:
        if only and not any(p == o or p.startswith(o.rstrip("/") + "/") for o in only):
            continue
        if exclude and any(fnmatch.fnmatch(p, g) or fnmatch.fnmatch(p.rsplit("/", 1)[-1], g) for g in exclude):
            continue
        out.append(p)
    return out


def make_batches(files, batch_lines):
    """Group files (already ordered) into batches of about batch_lines lines. Long files are split."""
    batches, cur, used = [], [], 0

    def flush():
        nonlocal cur, used
        if cur:
            batches.append(cur)
        cur, used = [], 0

    for f in files:
        total = f["peek"] if f["status"] == "peek" else f["lines"]
        if total > batch_lines:
            flush()
            start = 1
            while start <= total:
                end = min(start + batch_lines - 1, total)
                batches.append([{"path": f["path"], "start": start, "end": end, "of": f["lines"],
                                 "peek": f["status"] == "peek"}])
                start = end + 1
            continue
        if cur and used + total > batch_lines:
            flush()
        cur.append({"path": f["path"], "start": 1, "end": total, "of": f["lines"], "peek": f["status"] == "peek"})
        used += total
    flush()
    return batches


def git_facts(root):
    facts = {}
    head = run_git(root, "rev-parse", "--short", "HEAD")
    if not head:
        return facts
    facts["head"] = head.strip()
    branch = run_git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if branch:
        facts["branch"] = branch.strip()
    remote = run_git(root, "config", "--get", "remote.origin.url")
    if remote:
        facts["remote"] = re.sub(r"//[^/@\s]+@", "//", remote.strip())
    count = run_git(root, "rev-list", "--count", "HEAD")
    if count:
        facts["commits"] = int(count.strip() or 0)
    last = run_git(root, "log", "-1", "--format=%cs")
    first = run_git(root, "log", "--reverse", "--format=%cs", "--max-parents=0")
    if last:
        facts["last_commit"] = last.strip()
    if first and first.strip():
        facts["first_commit"] = first.strip().splitlines()[0]
    shallow = run_git(root, "rev-parse", "--is-shallow-repository")
    if shallow and shallow.strip() == "true":
        facts["shallow"] = True
    log = run_git(root, "-c", "core.quotepath=off", "log", "-n", "1000", "--name-only", "--format=", timeout=120)
    if log:
        counts = {}
        for line in log.splitlines():
            if line.strip():
                counts[line.strip()] = counts.get(line.strip(), 0) + 1
        top = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:15]
        facts["most_changed"] = [{"path": p, "commits": n} for p, n in top if n > 1]
    return facts


def folder_table(files, depth=2):
    rows = {}
    for f in files:
        parts = f["path"].split("/")[:-1]
        key = "/".join(parts[:depth]) if parts else "(root)"
        r = rows.setdefault(key, {"folder": key, "files": 0, "read_files": 0, "lines": 0})
        r["files"] += 1
        if f["status"] == "read":
            r["read_files"] += 1
            r["lines"] += f["lines"]
    return sorted(rows.values(), key=lambda r: (r["folder"] != "(root)", r["folder"]))


