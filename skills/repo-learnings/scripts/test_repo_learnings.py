def put(root, rel, text="", binary=None):
    path = os.path.join(root, *rel.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(binary if binary is not None else text.encode("utf-8"))


def run(*argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = rl.main(list(argv))
    return code, out.getvalue(), err.getvalue()


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="repo-learnings-test-")
        self.repo = os.path.join(self.tmp, "demo")
        self.out = os.path.join(self.tmp, "out")
        os.makedirs(self.repo)
        put(self.repo, "README.md", "# Demo\n\nA demo project.\n")
        put(self.repo, "pyproject.toml", "[project]\nname = 'demo'\n")
        put(self.repo, "src/app/main.py", "def main():\n    return 1\n\nclass App:\n    pass\n")
        put(self.repo, "src/app/util.py", "def helper(x):\n    return x\n")
        put(self.repo, "tests/test_util.py", "def test_helper():\n    assert True\n")
        put(self.repo, "docs/guide.md", "# Guide\n")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def manifest(self, **kw):
        kw.setdefault("use_git", False)
        return rl.build_manifest(self.repo, "demo", **kw)

    def by_path(self, m):
        return dict((f["path"], f) for f in m["files"])


class ClassifyTests(Base):
    def test_text_file_is_read_with_symbols(self):
        f = self.by_path(self.manifest())["src/app/main.py"]
        self.assertEqual(f["status"], "read")
        self.assertEqual(f["lines"], 5)
        self.assertEqual(f["lang"], "Python")
        self.assertEqual(f["symbols"], ["main", "App"])

    def test_binary_by_extension_and_by_content(self):
        put(self.repo, "logo.png", binary=b"\x89PNG....")
        put(self.repo, "blob.xyz", binary=b"abc\x00def")
        files = self.by_path(self.manifest())
        self.assertEqual((files["logo.png"]["status"], files["logo.png"]["reason"]), ("skip", "binary"))
        self.assertEqual(files["blob.xyz"]["reason"], "binary")

    def test_sensitive_files_are_not_opened(self):
        put(self.repo, ".env", "TOKEN=abc\n")
        put(self.repo, "deploy/server.pem", "-----BEGIN PRIVATE KEY-----\n")
        put(self.repo, ".env.example", "TOKEN=\n")
        files = self.by_path(self.manifest())
        self.assertEqual(files[".env"]["reason"], "sensitive")
        self.assertEqual(files[".env"]["lines"], 0)
        self.assertEqual(files["deploy/server.pem"]["reason"], "sensitive")
        self.assertEqual(files[".env.example"]["status"], "read")

    def test_lockfile_vendored_empty(self):
        put(self.repo, "package-lock.json", "{\n}\n")
        put(self.repo, "vendor/lib/x.js", "var a = 1;\n")
        put(self.repo, "src/empty.py", "")
        files = self.by_path(self.manifest())
        self.assertEqual(files["package-lock.json"]["reason"], "lockfile")
        self.assertEqual(files["vendor/lib/x.js"]["reason"], "vendored")
        self.assertEqual(files["src/empty.py"]["reason"], "empty")

    def test_generated_and_large_data_are_peeked(self):
        put(self.repo, "src/api_pb2.py", "x = 1\n" * 100)
        put(self.repo, "src/gen.py", "# Code generated by tool. DO NOT EDIT.\n" + "x = 1\n" * 10)
        put(self.repo, "data/rows.csv", "a,b\n" * 1000)
        files = self.by_path(self.manifest())
        self.assertEqual((files["src/api_pb2.py"]["status"], files["src/api_pb2.py"]["peek"]), ("peek", 40))
        self.assertEqual(files["src/gen.py"]["reason"], "generated")
        self.assertEqual((files["data/rows.csv"]["reason"], files["data/rows.csv"]["peek"]), ("large data file", 60))

    def test_include_forces_full_read(self):
        put(self.repo, "data/rows.csv", "a,b\n" * 1000)
        files = self.by_path(self.manifest(include=["data/*.csv"]))
        self.assertEqual(files["data/rows.csv"]["status"], "read")

    def test_hard_skip_dirs_are_not_walked(self):
        put(self.repo, "node_modules/x/index.js", "x\n")
        put(self.repo, ".git/config", "[core]\n")
        files = self.by_path(self.manifest())
        self.assertNotIn("node_modules/x/index.js", files)
        self.assertNotIn(".git/config", files)


class PlanTests(Base):
    def test_reading_order(self):
        m = self.manifest()
        order = [e["path"] for b in m["batches"] for e in b]
        self.assertEqual(order[0], "README.md")
        self.assertLess(order.index("pyproject.toml"), order.index("docs/guide.md"))
        self.assertLess(order.index("src/app/main.py"), order.index("src/app/util.py"))
        self.assertEqual(order[-1], "tests/test_util.py")

    def test_every_line_is_in_exactly_one_batch(self):
        put(self.repo, "src/big.py", "".join("x%d = 1\n" % i for i in range(250)))
        m = self.manifest(batch_lines=100)
        seen = {}
        for b in m["batches"]:
            self.assertLessEqual(sum(e["end"] - e["start"] + 1 for e in b), 100)
            for e in b:
                seen.setdefault(e["path"], []).append((e["start"], e["end"]))
        self.assertEqual(seen["src/big.py"], [(1, 100), (101, 200), (201, 250)])
        for f in m["files"]:
            if f["status"] == "read":
                self.assertEqual(sum(b - a + 1 for a, b in seen[f["path"]]), f["lines"])

    def test_only_and_exclude(self):
        m = self.manifest(only=["src"], exclude=["*util.py"])
        self.assertEqual([f["path"] for f in m["files"]], ["src/app/main.py"])

    def test_output_folder_inside_repo_is_left_out(self):
        inside = os.path.join(self.repo, "repo-learnings", "demo")
        os.makedirs(inside)
        put(self.repo, "repo-learnings/demo/LEARNINGS.md", "# old\n")
        m = self.manifest(out_dir=inside)
        self.assertFalse([f for f in m["files"] if f["path"].startswith("repo-learnings/")])

    def test_repo_name(self):
        self.assertEqual(rl.repo_name("https://github.com/owner/project.git"), "project")
        self.assertEqual(rl.repo_name("git@github.com:owner/project.git"), "project")
        self.assertEqual(rl.repo_name(r"C:\work\my repo"), "my-repo")


class CommandTests(Base):
    def scan(self, *extra):
        return run("scan", self.repo, "--out", self.out, "--no-git", *extra)

    def test_scan_writes_plan_manifest_and_skeleton(self):
        code, out, _ = self.scan()
        self.assertEqual(code, 0)
        self.assertIn("To read: 6 files", out)
        m = json.loads(rl.read(os.path.join(self.out, "manifest.json")))
        self.assertEqual(m["totals"]["read_files"], 6)
        plan = rl.read(os.path.join(self.out, "reading-plan.md"))
        self.assertIn("- [ ] `README.md`: 3 lines", plan)
        learn = rl.read(os.path.join(self.out, "LEARNINGS.md"))
        self.assertIn("| `src/app` | 2 |", learn)
        self.assertIn(rl.TODO, learn)

    def test_scan_keeps_existing_learnings_unless_forced(self):
        self.scan()
        path = os.path.join(self.out, "LEARNINGS.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write("my notes\n")
        self.scan()
        self.assertEqual(rl.read(path), "my notes\n")
        self.scan("--force")
        self.assertIn("# Learnings: demo", rl.read(path))

    def test_scan_errors(self):
        self.assertEqual(run("scan", os.path.join(self.tmp, "nope"), "--out", self.out)[0], 2)
        empty = os.path.join(self.tmp, "empty")
        os.makedirs(empty)
        self.assertEqual(run("scan", empty, "--out", self.out, "--no-git")[0], 2)
        self.assertEqual(run("next", os.path.join(self.tmp, "nothing"))[0], 2)

    def test_next_assemble_coverage_flow(self):
        self.scan("--batch-lines", "6")
        m = json.loads(rl.read(os.path.join(self.out, "manifest.json")))
        self.assertGreater(len(m["batches"]), 1)
        code, out, _ = run("next", self.out)
        self.assertIn("Batch 001", out)
        self.assertIn("README.md", out)
        code, out, _ = run("coverage", self.out)
        self.assertEqual(code, 1)
        self.assertIn("Files mentioned in the notes: 0 of 6", out)

        for i, b in enumerate(m["batches"], 1):
            with open(rl.notes_path(self.out, i), "w", encoding="utf-8") as f:
                f.write("".join("### %s\n\nNotes.\n\n" % e["path"] for e in b))
            code, out, _ = run("next", self.out)
            if i < len(m["batches"]):
                self.assertIn("Batch %03d" % (i + 1), out)
        self.assertIn("All %d batches have notes" % len(m["batches"]), out)

        code, out, _ = run("coverage", self.out)
        self.assertEqual(code, 1)                       # sections unfinished, notes not assembled
        self.assertIn("Files mentioned in the notes: 6 of 6", out)

        self.assertEqual(run("assemble", self.out)[0], 0)
        path = os.path.join(self.out, "LEARNINGS.md")
        text = rl.read(path)
        self.assertIn("### src/app/main.py", text)
        self.assertEqual(run("assemble", self.out)[0], 0)   # running twice does not duplicate
        text = rl.read(path)
        self.assertEqual(text.count("### src/app/main.py"), 1)

        with open(path, "w", encoding="utf-8") as f:
            f.write(text.replace(rl.TODO, "Done"))
        code, out, _ = run("coverage", self.out)
        self.assertEqual(code, 0)
        self.assertIn("Result: complete", out)

    def test_batch_command(self):
        self.scan()
        code, out, _ = run("batch", self.out, "1")
        self.assertEqual(code, 0)
        self.assertIn("src/app/main.py: main, App", out)
        self.assertEqual(run("batch", self.out, "99")[0], 2)


@unittest.skipUnless(shutil.which("git"), "git is not installed")
class GitTests(Base):
    def test_gitignore_is_respected_and_facts_are_read(self):
        def git(*a):
            subprocess.check_call(["git", "-C", self.repo, "-c", "user.name=t", "-c", "user.email=t@example.com",
                                   "-c", "commit.gpgsign=false"] + list(a),
                                  stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        put(self.repo, ".gitignore", "build/\n")
        put(self.repo, "build/out.js", "x\n")
        put(self.repo, "untracked.py", "y = 1\n")
        git("init", "-q")
        git("add", "README.md", ".gitignore", "src")
        git("commit", "-q", "-m", "first")
        m = rl.build_manifest(self.repo, "demo")
        paths = [f["path"] for f in m["files"]]
        self.assertEqual(m["listed_with"], "git ls-files")
        self.assertNotIn("build/out.js", paths)
        self.assertIn("untracked.py", paths)
        self.assertEqual(m["git"]["commits"], 1)


