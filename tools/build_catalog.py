def prompts_markdown(skills: list, categories: list) -> str:
    """examples/PROMPTS.md: every skill's example prompts, readable on GitHub."""
    total = sum(len(s["examples"]) for s in skills)
    out = ["# Example prompts", "",
           "<!-- Generated from examples/prompts.json by tools/build_catalog.py - do not edit by hand. -->", "",
           f"{total} things you can say to your AI coding agent, for all {len(skills)} skills. Install a skill "
           "([guide](../GUIDE.md)), then just ask: the agent loads the skill when your request matches its "
           "description. To force a skill, start with *\"Use the &lt;skill-name&gt; skill: …\"*.", "",
           "**Categories:** " + " · ".join(
               f"[{c['title']}](#{re.sub(r'[^a-z0-9 -]', '', c['title'].lower()).replace(' ', '-')})"
               for c in categories), ""]
    for c in categories:
        out += [f"## {c['title']}", "",
                f"Install the whole category: `--plugin {c['name']}`", ""]
        for s in sorted((s for s in skills if s["category"] == c["name"]), key=lambda s: s["title"].lower()):
            out += [f"### {s['title']}", "",
                    f"[`{s['name']}`](../{s['path']}/SKILL.md) · install: `--skill {s['name']}`", ""]
            out += [f"- “{p}”" for p in s["examples"]] + [""]
    return "\n".join(out)


def agents_table() -> str:
    """Markdown matrix of supported agents, from install.AGENTS."""
    rows = ["| Agent | `--agent` | Project folder | User folder | Also reads | MCP config (project / user) |",
            "|---|---|---|---|---|---|"]
    for k, a in AGENTS.items():
        also = ", ".join(f"`{p}`" for p in a["also_reads"]) or "-"
        user = f"`{a['global']}`" if a["global"] else "-"
        rows.append(f"| [{a['name']}]({a['docs']}) | `{k}` | `{a['project']}` | {user} | {also} | {mcp_cell(a)} |")
    return "\n".join(rows)


def mcp_cell(agent: dict) -> str:
    """'`project` / `user`' MCP config locations, linked to the vendor's MCP docs; '-' if none."""
    m = agent.get("mcp")
    if not m:
        return "-"
    user = m["global"]
    if isinstance(user, dict):
        user = f"{user['posix']}` (Windows: `{user['nt']}"
    return f"[`{m['project']}` / `{user}`]({m['docs']})"


def agents_table_simple() -> str:
    """Short 'where to copy' table for GUIDE.md (agents with their own entry; no 'universal')."""
    rows = ["| Agent | This project | Just me |", "|---|---|---|"]
    for k, a in AGENTS.items():
        if k == "universal":
            continue
        user = f"`{a['global']}/`" if a["global"] else "-"
        rows.append(f"| {a['name']} | `{a['project']}/` | {user} |")
    return "\n".join(rows)


def fill_block(text: str, name: str, table: str, where: str) -> str:
    start, end = f"<!-- {name}:start -->", f"<!-- {name}:end -->"
    pat = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if not pat.search(text):
        sys.exit(f"{where} is missing the {start} ... {end} markers")
    block = f"{start}\n<!-- Generated by tools/build_catalog.py -->\n{table}\n{end}"
    if "\n" not in table:                     # inline block: keep it on one line
        block = f"{start}{table}{end}"
    return pat.sub(lambda _: block, text)


def slug(title: str, name: str) -> str:
    """GitHub anchor of the heading '## <title> (`<name>`)' in skills/README.md."""
    return re.sub(r"[^a-z0-9 -]", "", f"{title} ({name})".lower()).replace(" ", "-")


def categories_table(catalog: dict) -> str:
    """README category table: one row per category plus one per bundle plugin."""
    desc = {p["name"]: " ".join(p["description"].split()) for p in catalog["plugins"]}
    rows = ["| Category (plugin) | Skills | What it covers |", "|---|---:|---|"]
    names = {c["name"] for c in catalog["categories"]}
    for c in catalog["categories"]:
        rows.append(f"| [`{c['name']}`](skills/README.md#{slug(c['title'], c['name'])}) | {c['count']} "
                    f"| {desc.get(c['name'], '')} |")
    for p in catalog["plugins"]:
        if p["name"] not in names:
            rows.append(f"| `{p['name']}` (bundle) | {len(p['skills'])} | {desc[p['name']]} |")
    return "\n".join(rows)


def plugins_table_simple(catalog: dict) -> str:
    """GUIDE.md table of every `--plugin` value, from the marketplace."""
    def short(text: str) -> str:
        text = " ".join(text.split()).replace("|", "\\|")
        return text if len(text) <= 170 else text[:167].rsplit(" ", 1)[0] + "..."
    rows = ["| Category | Skills | What's in it |", "|---|---:|---|"]
    rows += [f"| `{p['name']}` | {len(p['skills'])} | {short(p['description'])} |" for p in catalog["plugins"]]
    return "\n".join(rows)


def guide_text(text: str, catalog: dict) -> str:
    text = fill_block(text, "agents-simple", agents_table_simple(), "GUIDE.md")
    return fill_block(text, "plugins-simple", plugins_table_simple(catalog), "GUIDE.md")


def plugin_names_line(catalog: dict) -> str:
    return ", ".join(f"`{p['name']}`" for p in catalog["plugins"])


def readme_with_agents(text: str, catalog: dict) -> str:
    text = fill_block(text, "agents", agents_table(), "README.md")
    text = fill_block(text, "categories", categories_table(catalog), "README.md")
    text = fill_block(text, "plugin-names", plugin_names_line(catalog), "README.md")
    return fill_block(text, "counts", f"**{len(catalog['skills'])} skills in {len(catalog['plugins'])} plugins.**",
                      "README.md")

