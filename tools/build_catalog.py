        out.append({"id": k, "name": a["name"], "docs": a["docs"], "project": a["project"], "user": a["global"] or "",
                    "also_reads": a["also_reads"], "note": a.get("note", ""),
                    "mcp_project": m.get("project", ""), "mcp_user": user_mcp or "", "mcp_format": m.get("format", ""),
                    "mcp_docs": m.get("docs", "")})
